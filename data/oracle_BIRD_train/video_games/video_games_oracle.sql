CREATE TABLE "GENRE"
(ID         INTEGER   
            PRIMARY KEY,
    GENRE_NAME VARCHAR2(255) DEFAULT NULL
);

CREATE TABLE "GAME"
(ID        INTEGER   
            PRIMARY KEY,
    GENRE_ID  INTEGER          DEFAULT NULL,
    GAME_NAME VARCHAR2(255) DEFAULT NULL,
    FOREIGN KEY (GENRE_ID) REFERENCES "GENRE"(ID)
);

CREATE TABLE "PLATFORM"
(ID            INTEGER   
            PRIMARY KEY,
    PLATFORM_NAME VARCHAR2(255) DEFAULT NULL
);

CREATE TABLE "PUBLISHER"
(ID             INTEGER   
            PRIMARY KEY,
    PUBLISHER_NAME VARCHAR2(255) DEFAULT NULL
);

CREATE TABLE "GAME_PUBLISHER"
(ID           INTEGER   
            PRIMARY KEY,
    GAME_ID      INTEGER DEFAULT NULL,
    PUBLISHER_ID INTEGER DEFAULT NULL,
    FOREIGN KEY (GAME_ID) REFERENCES "GAME"(ID),
    FOREIGN KEY (PUBLISHER_ID) REFERENCES "PUBLISHER"(ID)
);

CREATE TABLE "GAME_PLATFORM"
(ID                INTEGER   
            PRIMARY KEY,
    GAME_PUBLISHER_ID INTEGER DEFAULT NULL,
    PLATFORM_ID       INTEGER DEFAULT NULL,
    RELEASE_YEAR      INTEGER DEFAULT NULL,
    FOREIGN KEY (GAME_PUBLISHER_ID) REFERENCES "GAME_PUBLISHER"(ID),
    FOREIGN KEY (PLATFORM_ID) REFERENCES "PLATFORM"(ID)
);

CREATE TABLE "REGION"
(ID          INTEGER   
            PRIMARY KEY,
    REGION_NAME VARCHAR2(255) DEFAULT NULL
);

CREATE TABLE "REGION_SALES"
(REGION_ID        INTEGER           DEFAULT NULL,
    GAME_PLATFORM_ID INTEGER           DEFAULT NULL,
    NUM_SALES        FLOAT DEFAULT NULL,
    FOREIGN KEY (GAME_PLATFORM_ID) REFERENCES "GAME_PLATFORM"(ID),
    FOREIGN KEY (REGION_ID) REFERENCES "REGION"(ID)
);

