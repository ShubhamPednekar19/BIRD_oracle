CREATE TABLE "CITY"
(ID        INTEGER   
            PRIMARY KEY,
    CITY_NAME VARCHAR2(255) DEFAULT NULL
);

CREATE TABLE "GAMES"
(ID         INTEGER   
            PRIMARY KEY,
    GAMES_YEAR INTEGER          DEFAULT NULL,
    GAMES_NAME VARCHAR2(255) DEFAULT NULL,
    SEASON     VARCHAR2(255) DEFAULT NULL
);

CREATE TABLE "GAMES_CITY"
(GAMES_ID INTEGER DEFAULT NULL,
    CITY_ID  INTEGER DEFAULT NULL,
    FOREIGN KEY (CITY_ID) REFERENCES "CITY"(ID),
    FOREIGN KEY (GAMES_ID) REFERENCES "GAMES"(ID)
);

CREATE TABLE "MEDAL"
(ID         INTEGER   
            PRIMARY KEY,
    MEDAL_NAME VARCHAR2(255) DEFAULT NULL
);

CREATE TABLE "NOC_REGION"
(ID          INTEGER   
            PRIMARY KEY,
    NOC         VARCHAR2(255)   DEFAULT NULL,
    REGION_NAME VARCHAR2(255) DEFAULT NULL
);

CREATE TABLE "PERSON"
(ID        INTEGER   
        PRIMARY KEY,
    FULL_NAME VARCHAR2(255) DEFAULT NULL,
    GENDER    VARCHAR2(255)  DEFAULT NULL,
    HEIGHT    INTEGER          DEFAULT NULL,
    WEIGHT    INTEGER          DEFAULT NULL
);

CREATE TABLE "GAMES_COMPETITOR"
(ID        INTEGER   
            PRIMARY KEY,
    GAMES_ID  INTEGER DEFAULT NULL,
    PERSON_ID INTEGER DEFAULT NULL,
    AGE       INTEGER DEFAULT NULL,
    FOREIGN KEY (GAMES_ID) REFERENCES "GAMES"(ID),
    FOREIGN KEY (PERSON_ID) REFERENCES "PERSON"(ID)
);

CREATE TABLE "PERSON_REGION"
(PERSON_ID INTEGER DEFAULT NULL,
    REGION_ID INTEGER DEFAULT NULL,
    FOREIGN KEY (PERSON_ID) REFERENCES "PERSON"(ID),
    FOREIGN KEY (REGION_ID) REFERENCES "NOC_REGION"(ID)
);

CREATE TABLE "SPORT"
(ID         INTEGER   
            PRIMARY KEY,
    SPORT_NAME VARCHAR2(255) DEFAULT NULL
);

CREATE TABLE "EVENT"
(ID         INTEGER   
            PRIMARY KEY,
    SPORT_ID   INTEGER          DEFAULT NULL,
    EVENT_NAME VARCHAR2(255) DEFAULT NULL,
    FOREIGN KEY (SPORT_ID) REFERENCES "SPORT"(ID)
);

CREATE TABLE "COMPETITOR_EVENT"
(EVENT_ID      INTEGER DEFAULT NULL,
    COMPETITOR_ID INTEGER DEFAULT NULL,
    MEDAL_ID      INTEGER DEFAULT NULL,
    FOREIGN KEY (COMPETITOR_ID) REFERENCES "GAMES_COMPETITOR"(ID),
    FOREIGN KEY (EVENT_ID) REFERENCES "EVENT"(ID),
    FOREIGN KEY (MEDAL_ID) REFERENCES "MEDAL"(ID)
);

