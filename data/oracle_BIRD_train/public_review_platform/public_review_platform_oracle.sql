CREATE TABLE "ATTRIBUTES"
(ATTRIBUTE_ID   INTEGER
        CONSTRAINT ATTRIBUTES_PK
            PRIMARY KEY,
    ATTRIBUTE_NAME VARCHAR2(255)
);

CREATE TABLE "BUSINESS"
(BUSINESS_ID  INTEGER
        CONSTRAINT BUSINESS_PK
            PRIMARY KEY,
    ACTIVE       VARCHAR2(255),
    CITY         VARCHAR2(255),
    STATE        VARCHAR2(255),
    STARS        FLOAT,
    REVIEW_COUNT VARCHAR2(255)
);

CREATE TABLE "USERS"
(USER_ID                 INTEGER
        CONSTRAINT USERS_PK
            PRIMARY KEY,
    USER_YELPING_SINCE_YEAR INTEGER,
    USER_AVERAGE_STARS      VARCHAR2(255),
    USER_VOTES_FUNNY        VARCHAR2(255),
    USER_VOTES_USEFUL       VARCHAR2(255),
    USER_VOTES_COOL         VARCHAR2(255),
    USER_REVIEW_COUNT       VARCHAR2(255),
    USER_FANS               VARCHAR2(255)
);

CREATE TABLE "CATEGORIES"
(CATEGORY_ID   INTEGER
        CONSTRAINT CATEGORIES_PK
            PRIMARY KEY,
    CATEGORY_NAME VARCHAR2(255)
);

CREATE TABLE "COMPLIMENTS"
(COMPLIMENT_ID   INTEGER
        CONSTRAINT COMPLIMENTS_PK
            PRIMARY KEY,
    COMPLIMENT_TYPE VARCHAR2(255)
);

CREATE TABLE "DAYS"
(DAY_ID      INTEGER
        CONSTRAINT DAYS_PK
            PRIMARY KEY,
    DAY_OF_WEEK VARCHAR2(255)
);

CREATE TABLE "YEARS"
(YEAR_ID     INTEGER
        CONSTRAINT YEARS_PK
            PRIMARY KEY,
    ACTUAL_YEAR INTEGER
);

CREATE TABLE "BUSINESS_ATTRIBUTES"
(ATTRIBUTE_ID    INTEGER
        CONSTRAINT BUSINESS_ATTRIBUTES_ATTRIBUTES_ATTRIBUTE_ID_FK
            REFERENCES "ATTRIBUTES",
    BUSINESS_ID     INTEGER
        CONSTRAINT BUSINESS_ATTRIBUTES_BUSINESS_BUSINESS_ID_FK
            REFERENCES "BUSINESS",
    ATTRIBUTE_VALUE VARCHAR2(255),
    CONSTRAINT BUSINESS_ATTRIBUTES_PK
        PRIMARY KEY (ATTRIBUTE_ID, BUSINESS_ID)
);

CREATE TABLE "BUSINESS_CATEGORIES"
(BUSINESS_ID INTEGER
        CONSTRAINT BUSINESS_CATEGORIES_BUSINESS_BUSINESS_ID_FK
            REFERENCES "BUSINESS",
    CATEGORY_ID INTEGER
        CONSTRAINT BUSINESS_CATEGORIES_CATEGORIES_CATEGORY_ID_FK
            REFERENCES "CATEGORIES",
    CONSTRAINT BUSINESS_CATEGORIES_PK
        PRIMARY KEY (BUSINESS_ID, CATEGORY_ID)
);

CREATE TABLE "BUSINESS_HOURS"
