CREATE TABLE "LOCATION"
(LOCATIONID INTEGER
        
            PRIMARY KEY,
    COUNTRY    VARCHAR2(255),
    STATE      VARCHAR2(255),
    STATECODE  VARCHAR2(255),
    CITY       VARCHAR2(255)
);

CREATE TABLE "USER"
(USERID VARCHAR2(255)
        CONSTRAINT USER_PK
            PRIMARY KEY,
    GENDER VARCHAR2(255)
);

CREATE TABLE "TWITTER"
(TWEETID         VARCHAR2(255)
            PRIMARY KEY,
    WEEKDAY         VARCHAR2(255),
    HOUR         INTEGER,
    DAY          INTEGER,
    LANG         VARCHAR2(255),
    ISRESHARE    VARCHAR2(255),
    REACH        INTEGER,
    RETWEETCOUNT INTEGER,
    LIKES        INTEGER,
    KLOUT        INTEGER,
    SENTIMENT    FLOAT,
    TEXT         VARCHAR2(255),
    LOCATIONID   INTEGER,
    USERID       VARCHAR2(255),
    FOREIGN KEY (LOCATIONID) REFERENCES "LOCATION"(LOCATIONID),
    FOREIGN KEY (USERID) REFERENCES "USER"(USERID)
);

