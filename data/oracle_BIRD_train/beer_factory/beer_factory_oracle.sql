CREATE TABLE "CUSTOMERS"
(CUSTOMERID            INTEGER
            PRIMARY KEY,
    FIRST                 VARCHAR2(255),
    LAST                  VARCHAR2(255),
    STREETADDRESS         VARCHAR2(255),
    CITY                  VARCHAR2(255),
    STATE                 VARCHAR2(255),
    ZIPCODE               INTEGER,
    EMAIL                 VARCHAR2(255),
    PHONENUMBER           VARCHAR2(255),
    FIRSTPURCHASEDATE     DATE,
    SUBSCRIBEDTOEMAILLIST VARCHAR2(255),
    GENDER                VARCHAR2(255)
);

CREATE TABLE "GEOLOCATION"
(LOCATIONID INTEGER
            PRIMARY KEY,
    LATITUDE   FLOAT, LONGITUDE FLOAT);

CREATE TABLE "LOCATION"
(LOCATIONID    INTEGER
            PRIMARY KEY,
    LOCATIONNAME  VARCHAR2(255),
    STREETADDRESS VARCHAR2(255),
    CITY          VARCHAR2(255),
    STATE         VARCHAR2(255),
    ZIPCODE       INTEGER,
    FOREIGN KEY (LOCATIONID) REFERENCES "GEOLOCATION"(LOCATIONID)
);

CREATE TABLE "ROOTBEERBRAND"
(BRANDID             INTEGER
            PRIMARY KEY,
    BRANDNAME           VARCHAR2(255),
    FIRSTBREWEDYEAR     INTEGER,
    BREWERYNAME         VARCHAR2(255),
    CITY                VARCHAR2(255),
    STATE               VARCHAR2(255),
    COUNTRY             VARCHAR2(255),
    DESCRIPTION         VARCHAR2(255),
    CANESUGAR           VARCHAR2(255),
    CORNSYRUP           VARCHAR2(255),
    HONEY               VARCHAR2(255),
    ARTIFICIALSWEETENER VARCHAR2(255),
    CAFFEINATED         VARCHAR2(255),
    ALCOHOLIC           VARCHAR2(255),
    AVAILABLEINCANS     VARCHAR2(255),
    AVAILABLEINBOTTLES  VARCHAR2(255),
    AVAILABLEINKEGS     VARCHAR2(255),
    WEBSITE             VARCHAR2(255),
    FACEBOOKPAGE        VARCHAR2(255),
    TWITTER             VARCHAR2(255),
    WHOLESALECOST       FLOAT,
    CURRENTRETAILPRICE  FLOAT
);

CREATE TABLE "ROOTBEER"
(ROOTBEERID    INTEGER
            PRIMARY KEY,
    BRANDID       INTEGER,
    CONTAINERTYPE VARCHAR2(255),
    LOCATIONID    INTEGER,
    PURCHASEDATE  DATE,
    FOREIGN KEY (LOCATIONID) REFERENCES "GEOLOCATION"(LOCATIONID),
    FOREIGN KEY (LOCATIONID) REFERENCES "LOCATION"(LOCATIONID),
    FOREIGN KEY (BRANDID) REFERENCES "ROOTBEERBRAND"(BRANDID)
);

CREATE TABLE "ROOTBEERREVIEW"
(CUSTOMERID INTEGER,
    BRANDID    INTEGER,
    STARRATING INTEGER,
    REVIEWDATE DATE,
    REVIEW     VARCHAR2(255),
    PRIMARY KEY (CUSTOMERID, BRANDID),
    FOREIGN KEY (CUSTOMERID) REFERENCES "CUSTOMERS"(CUSTOMERID),
    FOREIGN KEY (BRANDID) REFERENCES "ROOTBEERBRAND"(BRANDID)
);

CREATE TABLE "TRANSACTION"
(TRANSACTIONID    INTEGER
            PRIMARY KEY,
    CREDITCARDNUMBER INTEGER,
    CUSTOMERID       INTEGER,
    TRANSACTIONDATE  DATE,
    CREDITCARDTYPE   VARCHAR2(255),
    LOCATIONID       INTEGER,
    ROOTBEERID       INTEGER,
    PURCHASEPRICE    FLOAT,
    FOREIGN KEY (CUSTOMERID) REFERENCES "CUSTOMERS"(CUSTOMERID),
    FOREIGN KEY (LOCATIONID) REFERENCES "LOCATION"(LOCATIONID),
    FOREIGN KEY (ROOTBEERID) REFERENCES "ROOTBEER"(ROOTBEERID)
);

