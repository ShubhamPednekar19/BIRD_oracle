    ALPHA2CODE                                 VARCHAR2(255),
    CURRENCYUNIT                               VARCHAR2(255),
    SPECIALNOTES                               VARCHAR2(255),
    REGION                                     VARCHAR2(255),
    INCOMEGROUP                                VARCHAR2(255),
    WB2CODE                                    VARCHAR2(255),
    NATIONALACCOUNTSBASEYEAR                   VARCHAR2(255),
    NATIONALACCOUNTSREFERENCEYEAR              VARCHAR2(255),
    SNAPRICEVALUATION                          VARCHAR2(255),
    LENDINGCATEGORY                            VARCHAR2(255),
    OTHERGROUPS                                VARCHAR2(255),
    SYSTEMOFNATIONALACCOUNTS                   VARCHAR2(255),
    ALTERNATIVECONVERSIONFACTOR                VARCHAR2(255),
    PPPSURVEYYEAR                              VARCHAR2(255),
    BALANCEOFPAYMENTSMANUALINUSE               VARCHAR2(255),
    EXTERNALDEBTREPORTINGSTATUS                VARCHAR2(255),
    SYSTEMOFTRADE                              VARCHAR2(255),
    GOVERNMENTACCOUNTINGCONCEPT                VARCHAR2(255),
    IMFDATADISSEMINATIONSTANDARD               VARCHAR2(255),
    LATESTPOPULATIONCENSUS                     VARCHAR2(255),
    LATESTHOUSEHOLDSURVEY                      VARCHAR2(255),
    SOURCEOFMOSTRECENTINCOMEANDEXPENDITUREDATA VARCHAR2(255),
    VITALREGISTRATIONCOMPLETE                  VARCHAR2(255),
    LATESTAGRICULTURALCENSUS                   VARCHAR2(255),
    LATESTINDUSTRIALDATA                       INTEGER,
    LATESTTRADEDATA                            INTEGER,
    LATESTWATERWITHDRAWALDATA                  INTEGER
);

CREATE TABLE "SERIES"
(SERIESCODE                       VARCHAR2(255)   
        PRIMARY KEY,
    TOPIC                            VARCHAR2(255),
    INDICATORNAME                    VARCHAR2(255),
    SHORTDEFINITION                  VARCHAR2(255),
    LONGDEFINITION                   VARCHAR2(255),
    UNITOFMEASURE                    VARCHAR2(255),
    PERIODICITY                      VARCHAR2(255),
    BASEPERIOD                       VARCHAR2(255),
    OTHERNOTES                       INTEGER,
    AGGREGATIONMETHOD                VARCHAR2(255),
    LIMITATIONSANDEXCEPTIONS         VARCHAR2(255),
    NOTESFROMORIGINALSOURCE          VARCHAR2(255),
    GENERALCOMMENTS                  VARCHAR2(255),
    SOURCE                           VARCHAR2(255),
    STATISTICALCONCEPTANDMETHODOLOGY VARCHAR2(255),
    DEVELOPMENTRELEVANCE             VARCHAR2(255),
    RELATEDSOURCELINKS               VARCHAR2(255),
    OTHERWEBLINKS                    INTEGER,
    RELATEDINDICATORS                INTEGER,
    LICENSETYPE                      VARCHAR2(255)
);

CREATE TABLE "COUNTRYNOTES"
(COUNTRYCODE VARCHAR2(255)    ,
    SERIESCODE  VARCHAR2(255)    ,
    DESCRIPTION VARCHAR2(255),
    PRIMARY KEY (COUNTRYCODE, SERIESCODE),
    FOREIGN KEY (SERIESCODE) REFERENCES "SERIES"(SERIESCODE),
    FOREIGN KEY (COUNTRYCODE) REFERENCES "COUNTRY"(COUNTRYCODE)
);

CREATE TABLE "FOOTNOTES"
(COUNTRYCODE VARCHAR2(255)    ,
    SERIESCODE  VARCHAR2(255)    ,
    YEAR        VARCHAR2(255),
    DESCRIPTION VARCHAR2(255),
    PRIMARY KEY (COUNTRYCODE, SERIESCODE, YEAR),
    FOREIGN KEY (SERIESCODE) REFERENCES "SERIES"(SERIESCODE),
    FOREIGN KEY (COUNTRYCODE) REFERENCES "COUNTRY"(COUNTRYCODE)
);

CREATE TABLE "INDICATORS"
(COUNTRYNAME   VARCHAR2(255),
    COUNTRYCODE   VARCHAR2(255)    ,
    INDICATORNAME VARCHAR2(255),
    INDICATORCODE VARCHAR2(255)    ,
    YEAR          INTEGER    ,
    VALUE         INTEGER,
    PRIMARY KEY (COUNTRYCODE, INDICATORCODE, YEAR),
    FOREIGN KEY (COUNTRYCODE) REFERENCES "COUNTRY"(COUNTRYCODE)
);

CREATE TABLE "SERIESNOTES"
(SERIESCODE  VARCHAR2(255)    ,
    YEAR        VARCHAR2(255)    ,
    DESCRIPTION VARCHAR2(255),
    PRIMARY KEY (SERIESCODE, YEAR),
    FOREIGN KEY (SERIESCODE) REFERENCES "SERIES"(SERIESCODE)
);

