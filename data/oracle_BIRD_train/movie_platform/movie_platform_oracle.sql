CREATE TABLE "LISTS"
(USER_ID                     INTEGER,
    LIST_ID                     INTEGER   
        PRIMARY KEY,
    LIST_TITLE                  VARCHAR2(255),
    LIST_MOVIE_NUMBER           INTEGER,
    LIST_UPDATE_TIMESTAMP_UTC   VARCHAR2(255),
    LIST_CREATION_TIMESTAMP_UTC VARCHAR2(255),
    LIST_FOLLOWERS              INTEGER,
    LIST_URL                    VARCHAR2(255),
    LIST_COMMENTS               INTEGER,
    LIST_DESCRIPTION            VARCHAR2(255),
    LIST_COVER_IMAGE_URL        VARCHAR2(255),
    LIST_FIRST_IMAGE_URL        VARCHAR2(255),
    LIST_SECOND_IMAGE_URL       VARCHAR2(255),
    LIST_THIRD_IMAGE_URL        VARCHAR2(255)
);

CREATE TABLE "MOVIES"
(MOVIE_ID             INTEGER   
        PRIMARY KEY,
    MOVIE_TITLE          VARCHAR2(255),
    MOVIE_RELEASE_YEAR   INTEGER,
    MOVIE_URL            VARCHAR2(255),
    MOVIE_TITLE_LANGUAGE VARCHAR2(255),
    MOVIE_POPULARITY     INTEGER,
    MOVIE_IMAGE_URL      VARCHAR2(255),
    DIRECTOR_ID          VARCHAR2(255),
    DIRECTOR_NAME        VARCHAR2(255),
    DIRECTOR_URL         VARCHAR2(255)
);

CREATE TABLE "RATINGS_USERS"
(USER_ID                     INTEGER,
    RATING_DATE_UTC         VARCHAR2(255),
    USER_TRIALIST           INTEGER,
    USER_SUBSCRIBER         INTEGER,
    USER_AVATAR_IMAGE_URL   VARCHAR2(255),
    USER_COVER_IMAGE_URL    VARCHAR2(255),
    USER_ELIGIBLE_FOR_TRIAL INTEGER,
    USER_HAS_PAYMENT_METHOD INTEGER
);

CREATE TABLE "LISTS_USERS"
(USER_ID                 INTEGER  PRIMARY KEY,
    LIST_ID                 INTEGER    ,
    LIST_UPDATE_DATE_UTC    VARCHAR2(255),
    LIST_CREATION_DATE_UTC  VARCHAR2(255),
    USER_TRIALIST           INTEGER,
    USER_SUBSCRIBER         INTEGER,
    USER_AVATAR_IMAGE_URL   VARCHAR2(255),
    USER_COVER_IMAGE_URL    VARCHAR2(255),
    USER_ELIGIBLE_FOR_TRIAL VARCHAR2(255),
    USER_HAS_PAYMENT_METHOD VARCHAR2(255),
    
    FOREIGN KEY (LIST_ID) REFERENCES "LISTS"(LIST_ID)
);

CREATE TABLE "RATINGS"
(MOVIE_ID                INTEGER,
    RATING_ID               INTEGER,
    RATING_URL              VARCHAR2(255),
    RATING_SCORE            INTEGER,
    RATING_TIMESTAMP_UTC    VARCHAR2(255),
    CRITIC                  VARCHAR2(255),
    CRITIC_LIKES            INTEGER,
    CRITIC_COMMENTS         INTEGER,
    USER_ID                 INTEGER,
    USER_TRIALIST           INTEGER,
    USER_SUBSCRIBER         INTEGER,
    USER_ELIGIBLE_FOR_TRIAL INTEGER,
    USER_HAS_PAYMENT_METHOD INTEGER,
    FOREIGN KEY (MOVIE_ID) REFERENCES "MOVIES"(MOVIE_ID),
    FOREIGN KEY (USER_ID) REFERENCES "LISTS_USERS"(USER_ID)
);

