CREATE TABLE "PLAYSTORE"
(APP              VARCHAR2(255) PRIMARY KEY,
    CATEGORY         VARCHAR2(255),
    RATING           FLOAT,
    REVIEWS          INTEGER,
    "SIZE"             VARCHAR2(255),
    INSTALLS         VARCHAR2(255),
    "TYPE"             VARCHAR2(255),
    PRICE            VARCHAR2(255),
    "CONTENT RATING" VARCHAR2(255),
    GENRES           VARCHAR2(255)
);

CREATE TABLE "PLAYSTORE_USER_REVIEWS"
(APP                    VARCHAR2(255)
        REFERENCES "PLAYSTORE" (APP),
    TRANSLATED_REVIEW      VARCHAR2(255),
    SENTIMENT              VARCHAR2(255),
    SENTIMENT_POLARITY     VARCHAR2(255),
    SENTIMENT_SUBJECTIVITY VARCHAR2(255)
);

