CREATE TABLE "COUNTRY"
(ORIGIN  INTEGER
            PRIMARY KEY,
    COUNTRY VARCHAR2(255)
);

CREATE TABLE "PRICE"
(ID    INTEGER
            PRIMARY KEY,
    PRICE FLOAT
);

CREATE TABLE "DATA"
(ID           INTEGER
            PRIMARY KEY,
    MPG          FLOAT,
    CYLINDERS    INTEGER,
    DISPLACEMENT FLOAT,
    HORSEPOWER   INTEGER,
    WEIGHT       INTEGER,
    ACCELERATION FLOAT,
    MODEL        INTEGER,
    CAR_NAME     VARCHAR2(255),
    FOREIGN KEY (ID) REFERENCES "PRICE"(ID)
);

CREATE TABLE "PRODUCTION"
(ID         INTEGER,
    MODEL_YEAR INTEGER,
    COUNTRY    INTEGER,
    PRIMARY KEY (ID, MODEL_YEAR),
    FOREIGN KEY (COUNTRY) REFERENCES "COUNTRY"(ORIGIN),
    FOREIGN KEY (ID) REFERENCES "DATA"(ID),
    FOREIGN KEY (ID) REFERENCES "PRICE"(ID)
);

