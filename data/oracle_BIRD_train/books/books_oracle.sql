CREATE TABLE "ADDRESS_STATUS"
(STATUS_ID      INTEGER
            PRIMARY KEY,
    ADDRESS_STATUS VARCHAR2(255)
);

CREATE TABLE "AUTHOR"
(AUTHOR_ID   INTEGER
            PRIMARY KEY,
    AUTHOR_NAME VARCHAR2(255)
);

CREATE TABLE "BOOK_LANGUAGE"
(LANGUAGE_ID   INTEGER
            PRIMARY KEY,
    LANGUAGE_CODE VARCHAR2(255),
    LANGUAGE_NAME VARCHAR2(255)
);

CREATE TABLE "COUNTRY"
(COUNTRY_ID   INTEGER
            PRIMARY KEY,
    COUNTRY_NAME VARCHAR2(255)
);

CREATE TABLE "ADDRESS"
(ADDRESS_ID    INTEGER
            PRIMARY KEY,
    STREET_NUMBER VARCHAR2(255),
    STREET_NAME   VARCHAR2(255),
    CITY          VARCHAR2(255),
    COUNTRY_ID    INTEGER,
    FOREIGN KEY (COUNTRY_ID) REFERENCES "COUNTRY"(COUNTRY_ID)
);

CREATE TABLE "CUSTOMER"
(CUSTOMER_ID INTEGER
            PRIMARY KEY,
    FIRST_NAME  VARCHAR2(255),
    LAST_NAME   VARCHAR2(255),
    EMAIL       VARCHAR2(255)
);

CREATE TABLE "CUSTOMER_ADDRESS"
(CUSTOMER_ID INTEGER,
    ADDRESS_ID  INTEGER,
    STATUS_ID   INTEGER,
    PRIMARY KEY (CUSTOMER_ID, ADDRESS_ID),
    FOREIGN KEY (ADDRESS_ID) REFERENCES "ADDRESS"(ADDRESS_ID),
    FOREIGN KEY (CUSTOMER_ID) REFERENCES "CUSTOMER"(CUSTOMER_ID)
);

CREATE TABLE "ORDER_STATUS"
(STATUS_ID    INTEGER
            PRIMARY KEY,
    STATUS_VALUE VARCHAR2(255)
);

CREATE TABLE "PUBLISHER"
(PUBLISHER_ID   INTEGER
            PRIMARY KEY,
    PUBLISHER_NAME VARCHAR2(255)
);

CREATE TABLE "BOOK"
(BOOK_ID          INTEGER
            PRIMARY KEY,
    TITLE            VARCHAR2(255),
    ISBN13           VARCHAR2(255),
    LANGUAGE_ID      INTEGER,
    NUM_PAGES        INTEGER,
    PUBLICATION_DATE DATE,
    PUBLISHER_ID     INTEGER,
    FOREIGN KEY (LANGUAGE_ID) REFERENCES "BOOK_LANGUAGE"(LANGUAGE_ID),
    FOREIGN KEY (PUBLISHER_ID) REFERENCES "PUBLISHER"(PUBLISHER_ID)
);

CREATE TABLE "BOOK_AUTHOR"
(BOOK_ID   INTEGER,
    AUTHOR_ID INTEGER,
    PRIMARY KEY (BOOK_ID, AUTHOR_ID),
    FOREIGN KEY (AUTHOR_ID) REFERENCES "AUTHOR"(AUTHOR_ID),
    FOREIGN KEY (BOOK_ID) REFERENCES "BOOK"(BOOK_ID)
);

CREATE TABLE "SHIPPING_METHOD"
(METHOD_ID   INTEGER
            PRIMARY KEY,
    METHOD_NAME VARCHAR2(255),
    COST        FLOAT
);

CREATE TABLE "CUST_ORDER"
(ORDER_ID           INTEGER
        GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ORDER_DATE         TIMESTAMP,
    CUSTOMER_ID        INTEGER
        REFERENCES "CUSTOMER",
    SHIPPING_METHOD_ID INTEGER
        REFERENCES "SHIPPING_METHOD",
    DEST_ADDRESS_ID    INTEGER
        REFERENCES "ADDRESS"
);

CREATE TABLE "ORDER_HISTORY"
(HISTORY_ID  INTEGER
        GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ORDER_ID    INTEGER
        REFERENCES "CUST_ORDER",
    STATUS_ID   INTEGER
        REFERENCES "ORDER_STATUS",
    STATUS_DATE TIMESTAMP
);

CREATE TABLE "ORDER_LINE"
(LINE_ID  INTEGER
        GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ORDER_ID INTEGER
        REFERENCES "CUST_ORDER",
    BOOK_ID  INTEGER
        REFERENCES "BOOK",
    PRICE    FLOAT
);

