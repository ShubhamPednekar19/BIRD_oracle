CREATE TABLE "AUTHOR"
(ID          INTEGER
        CONSTRAINT AUTHOR_PK
            PRIMARY KEY,
    NAME        VARCHAR2(255),
    AFFILIATION VARCHAR2(255)
);

CREATE TABLE "CONFERENCE"
(ID        INTEGER
        CONSTRAINT CONFERENCE_PK
            PRIMARY KEY,
    SHORTNAME VARCHAR2(255),
    FULLNAME  VARCHAR2(255),
    HOMEPAGE  VARCHAR2(255)
);

CREATE TABLE "JOURNAL"
(ID        INTEGER
        CONSTRAINT JOURNAL_PK
            PRIMARY KEY,
    SHORTNAME VARCHAR2(255),
    FULLNAME  VARCHAR2(255),
    HOMEPAGE  VARCHAR2(255)
);

CREATE TABLE "PAPER"
(ID           INTEGER
            PRIMARY KEY,
    TITLE        VARCHAR2(255),
    YEAR         INTEGER,
    CONFERENCEID INTEGER,
    JOURNALID    INTEGER,
    KEYWORD      VARCHAR2(255),
    FOREIGN KEY (CONFERENCEID) REFERENCES "CONFERENCE"(ID),
    FOREIGN KEY (JOURNALID) REFERENCES "JOURNAL"(ID)
);

CREATE TABLE "PAPERAUTHOR"
(PAPERID     INTEGER,
    AUTHORID    INTEGER,
    NAME        VARCHAR2(255),
    AFFILIATION VARCHAR2(255),
    FOREIGN KEY (PAPERID) REFERENCES "PAPER"(ID),
    FOREIGN KEY (AUTHORID) REFERENCES "AUTHOR"(ID)
);

