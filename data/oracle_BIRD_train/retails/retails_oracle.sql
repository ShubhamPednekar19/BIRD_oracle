CREATE TABLE "PART"
(P_PARTKEY     INTEGER         NOT NULL  
        PRIMARY KEY,
    P_TYPE        VARCHAR2(255)    NULL,
    P_SIZE        INTEGER            NULL,
    P_BRAND       VARCHAR2(255)       NULL,
    P_NAME        VARCHAR2(255)    NULL,
    P_CONTAINER   VARCHAR2(255)       NULL,
    P_MFGR        VARCHAR2(255)       NULL,
    P_RETAILPRICE FLOAT NULL,
    P_COMMENT     VARCHAR2(255)    NULL
);

CREATE TABLE "REGION"
(R_REGIONKEY INTEGER          NOT NULL  
        PRIMARY KEY,
    R_NAME      VARCHAR2(255)     NULL,
    R_COMMENT   VARCHAR2(255) NULL
);

CREATE TABLE "NATION"
(N_NATIONKEY INTEGER          NOT NULL  
        PRIMARY KEY,
    N_NAME      VARCHAR2(255)     NULL,
    N_REGIONKEY INTEGER          NULL,
    N_COMMENT   VARCHAR2(255) NULL,
    FOREIGN KEY (N_REGIONKEY) REFERENCES "REGION" (R_REGIONKEY)
              ON DELETE CASCADE
);

CREATE TABLE "CUSTOMER" (C_CUSTKEY INTEGER NOT NULL  ,
  C_MKTSEGMENT VARCHAR2(255) DEFAULT NULL,
  C_NATIONKEY INTEGER DEFAULT NULL,
  C_NAME VARCHAR2(255) DEFAULT NULL,
  C_ADDRESS VARCHAR2(255) DEFAULT NULL,
  C_PHONE VARCHAR2(255) DEFAULT NULL,
  C_ACCTBAL FLOAT DEFAULT NULL,
  C_COMMENT VARCHAR2(255) DEFAULT NULL,
  PRIMARY KEY (C_CUSTKEY),
  FOREIGN KEY (C_NATIONKEY) REFERENCES "NATION" (N_NATIONKEY) ON DELETE CASCADE  
);

CREATE TABLE "ORDERS"
(O_ORDERDATE     DATE           NULL,
    O_ORDERKEY      INTEGER         NOT NULL  
        PRIMARY KEY,
    O_CUSTKEY       INTEGER         NOT NULL  ,
    O_ORDERPRIORITY VARCHAR2(255)       NULL,
    O_SHIPPRIORITY  INTEGER            NULL,
    O_CLERK         VARCHAR2(255)       NULL,
    O_ORDERSTATUS   VARCHAR2(255)           NULL,
    O_TOTALPRICE    FLOAT NULL,
    O_COMMENT       VARCHAR2(255)    NULL,
    FOREIGN KEY (O_CUSTKEY) REFERENCES "CUSTOMER" (C_CUSTKEY)
              ON DELETE CASCADE
);

CREATE TABLE "SUPPLIER"
(S_SUPPKEY   INTEGER            NOT NULL  
        PRIMARY KEY,
    S_NATIONKEY INTEGER            NULL,
    S_COMMENT   VARCHAR2(255)   NULL,
    S_NAME      VARCHAR2(255)       NULL,
    S_ADDRESS   VARCHAR2(255)    NULL,
    S_PHONE     VARCHAR2(255)       NULL,
    S_ACCTBAL   FLOAT NULL,
    FOREIGN KEY (S_NATIONKEY) REFERENCES "NATION" (N_NATIONKEY)
);

CREATE TABLE "PARTSUPP"
(PS_PARTKEY    INTEGER         NOT NULL  ,
    PS_SUPPKEY    INTEGER            NOT NULL  ,
    PS_SUPPLYCOST FLOAT NOT NULL  ,
    PS_AVAILQTY   INTEGER            NULL,
    PS_COMMENT    VARCHAR2(255)   NULL,
    PRIMARY KEY (PS_PARTKEY, PS_SUPPKEY),
    FOREIGN KEY (PS_PARTKEY) REFERENCES "PART" (P_PARTKEY)
              ON DELETE CASCADE,
    FOREIGN KEY (PS_SUPPKEY) REFERENCES "SUPPLIER" (S_SUPPKEY)
              ON DELETE CASCADE
);

CREATE TABLE "LINEITEM"
(L_SHIPDATE      DATE           NULL,
    L_ORDERKEY      INTEGER         NOT NULL  ,
    L_DISCOUNT      FLOAT NOT NULL  ,
    L_EXTENDEDPRICE FLOAT NOT NULL  ,
    L_SUPPKEY       INTEGER            NOT NULL  ,
    L_QUANTITY      INTEGER         NOT NULL  ,
    L_RETURNFLAG    VARCHAR2(255)           NULL,
    L_PARTKEY       INTEGER         NOT NULL  ,
    L_LINESTATUS    VARCHAR2(255)           NULL,
    L_TAX           FLOAT NOT NULL  ,
    L_COMMITDATE    DATE           NULL,
    L_RECEIPTDATE   DATE           NULL,
    L_SHIPMODE      VARCHAR2(255)       NULL,
    L_LINENUMBER    INTEGER         NOT NULL  ,
    L_SHIPINSTRUCT  VARCHAR2(255)       NULL,
    L_COMMENT       VARCHAR2(255)    NULL,
    PRIMARY KEY (L_ORDERKEY, L_LINENUMBER),
    FOREIGN KEY (L_ORDERKEY) REFERENCES "ORDERS" (O_ORDERKEY)
              ON DELETE CASCADE,
    FOREIGN KEY (L_PARTKEY, L_SUPPKEY) REFERENCES "PARTSUPP" (PS_PARTKEY, PS_SUPPKEY)
              ON DELETE CASCADE
);

