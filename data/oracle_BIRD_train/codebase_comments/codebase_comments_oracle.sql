CREATE TABLE "METHOD"
(ID            INTEGER 
        GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    NAME          VARCHAR2(255),
    FULLCOMMENT   VARCHAR2(255),
    SUMMARY       VARCHAR2(255),
    APICALLS      VARCHAR2(255),
    COMMENTISXML  INTEGER,
    SAMPLEDAT     INTEGER,
    SOLUTIONID    INTEGER,
    LANG          VARCHAR2(255),
    NAMETOKENIZED VARCHAR2(255)
);

CREATE TABLE "METHODPARAMETER"
(ID       INTEGER 
        GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    METHODID VARCHAR2(255),
    TYPE     VARCHAR2(255),
    NAME     VARCHAR2(255)
);

CREATE TABLE "REPO"
(ID            INTEGER 
        GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    URL           VARCHAR2(255),
    STARS         INTEGER,
    FORKS         INTEGER,
    WATCHERS      INTEGER,
    PROCESSEDTIME INTEGER
);

CREATE TABLE "SOLUTION"
(ID            INTEGER 
        GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    REPOID        INTEGER,
    PATH          VARCHAR2(255),
    PROCESSEDTIME INTEGER,
    WASCOMPILED   INTEGER
);

