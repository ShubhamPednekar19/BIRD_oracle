CREATE TABLE "AUTHORS"
(AU_ID    VARCHAR2(255)
        PRIMARY KEY,
    AU_LNAME VARCHAR2(255)   ,
    AU_FNAME VARCHAR2(255)   ,
    PHONE    VARCHAR2(255)      ,
    ADDRESS  VARCHAR2(255),
    CITY     VARCHAR2(255),
    STATE    VARCHAR2(255),
    ZIP      VARCHAR2(255),
    CONTRACT VARCHAR2(255)       
);

CREATE TABLE "JOBS"
(JOB_ID   INTEGER
        PRIMARY KEY,
    JOB_DESC VARCHAR2(255)   ,
    MIN_LVL  INTEGER       ,
    MAX_LVL  INTEGER       
);

CREATE TABLE "PUBLISHERS"
(PUB_ID   VARCHAR2(255)
        PRIMARY KEY,
    PUB_NAME VARCHAR2(255),
    CITY     VARCHAR2(255),
    STATE    VARCHAR2(255),
    COUNTRY  VARCHAR2(255)
);

CREATE TABLE "EMPLOYEE"
(EMP_ID    VARCHAR2(255)
        PRIMARY KEY,
    FNAME     VARCHAR2(255)   ,
    MINIT     VARCHAR2(255),
    LNAME     VARCHAR2(255)   ,
    JOB_ID    INTEGER       ,
    JOB_LVL   INTEGER,
    PUB_ID    VARCHAR2(255)       ,
    HIRE_DATE TIMESTAMP      ,
    FOREIGN KEY (JOB_ID) REFERENCES "JOBS"(JOB_ID)
              ON DELETE CASCADE,
    FOREIGN KEY (PUB_ID) REFERENCES "PUBLISHERS"(PUB_ID)
              ON DELETE CASCADE
);

CREATE TABLE "PUB_INFO"
(PUB_ID  VARCHAR2(255)
        PRIMARY KEY,
    LOGO    BLOB,
    PR_INFO VARCHAR2(255),
    FOREIGN KEY (PUB_ID) REFERENCES "PUBLISHERS"(PUB_ID)
              ON DELETE CASCADE
);

CREATE TABLE "STORES"
(STOR_ID     VARCHAR2(255)
        PRIMARY KEY,
    STOR_NAME    VARCHAR2(255),
    STOR_ADDRESS VARCHAR2(255),
    CITY         VARCHAR2(255),
    STATE        VARCHAR2(255),
    ZIP          VARCHAR2(255)
);

CREATE TABLE "DISCOUNTS"
(DISCOUNTTYPE VARCHAR2(255)     ,
    STOR_ID      VARCHAR2(255),
    LOWQTY       INTEGER,
    HIGHQTY      INTEGER,
    DISCOUNT     FLOAT   ,
    FOREIGN KEY (STOR_ID)  REFERENCES "STORES"(STOR_ID)
              ON DELETE CASCADE
);

CREATE TABLE "TITLES"
(TITLE_ID  VARCHAR2(255)
        PRIMARY KEY,
    TITLE     VARCHAR2(255)   ,
    TYPE      VARCHAR2(255)      ,
    PUB_ID    VARCHAR2(255),
    PRICE     FLOAT,
    ADVANCE   FLOAT,
    ROYALTY   INTEGER,
    YTD_SALES INTEGER,
    NOTES     VARCHAR2(255),
    PUBDATE   TIMESTAMP      ,
    FOREIGN KEY (PUB_ID) REFERENCES "PUBLISHERS"(PUB_ID)
              ON DELETE CASCADE
);

CREATE TABLE "ROYSCHED"
(TITLE_ID VARCHAR2(255)   ,
    LORANGE  INTEGER,
    HIRANGE  INTEGER,
    ROYALTY  INTEGER,
    FOREIGN KEY (TITLE_ID)  REFERENCES "TITLES"(TITLE_ID)
              ON DELETE CASCADE
);

CREATE TABLE "SALES"
(STOR_ID  VARCHAR2(255)       ,
    ORD_NUM  VARCHAR2(255)    ,
    ORD_DATE TIMESTAMP      ,
    QTY      INTEGER       ,
    PAYTERMS VARCHAR2(255)    ,
    TITLE_ID VARCHAR2(255)     ,
    PRIMARY KEY (STOR_ID, ORD_NUM, TITLE_ID),
    FOREIGN KEY (STOR_ID)   REFERENCES "STORES"(STOR_ID)
              ON DELETE CASCADE,
    FOREIGN KEY (TITLE_ID)  REFERENCES "TITLES"(TITLE_ID)
              ON DELETE CASCADE

);

CREATE TABLE "TITLEAUTHOR"
(AU_ID      VARCHAR2(255)   ,
    TITLE_ID   VARCHAR2(255)    ,
    AU_ORD     INTEGER,
    ROYALTYPER INTEGER,
    PRIMARY KEY (AU_ID, TITLE_ID),
    FOREIGN KEY (AU_ID) REFERENCES "AUTHORS"(AU_ID)
              ON DELETE CASCADE,
    FOREIGN KEY (TITLE_ID)    REFERENCES "TITLES" (TITLE_ID)
              ON DELETE CASCADE
);

