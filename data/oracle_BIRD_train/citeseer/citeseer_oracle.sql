CREATE TABLE "CITES"
(CITED_PAPER_ID  VARCHAR2(255)   ,
    CITING_PAPER_ID VARCHAR2(255)   ,
    PRIMARY KEY (CITED_PAPER_ID, CITING_PAPER_ID)
);

CREATE TABLE "PAPER"
(PAPER_ID    VARCHAR2(255)    
        PRIMARY KEY,
    CLASS_LABEL VARCHAR2(255)   
);

CREATE TABLE "CONTENT"
(PAPER_ID     VARCHAR2(255)   ,
    WORD_CITED_ID VARCHAR2(255)   ,
    PRIMARY KEY (PAPER_ID, WORD_CITED_ID),
    FOREIGN KEY (PAPER_ID) REFERENCES "PAPER"(PAPER_ID)
);

