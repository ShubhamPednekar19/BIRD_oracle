CREATE TABLE "PEOPLE"
("CUSTOMER ID"   VARCHAR2(255),
    "CUSTOMER NAME" VARCHAR2(255),
    SEGMENT         VARCHAR2(255),
    COUNTRY         VARCHAR2(255),
    CITY            VARCHAR2(255),
    STATE           VARCHAR2(255),
    "POSTAL CODE"   INTEGER,
    REGION          VARCHAR2(255),
    PRIMARY KEY ("CUSTOMER ID", REGION)
);

CREATE TABLE "PRODUCT"
("PRODUCT ID"   VARCHAR2(255),
    "PRODUCT NAME" VARCHAR2(255),
    CATEGORY       VARCHAR2(255),
    "SUB-CATEGORY" VARCHAR2(255),
    REGION         VARCHAR2(255),
    PRIMARY KEY ("PRODUCT ID", REGION)
);

CREATE TABLE "CENTRAL_SUPERSTORE"
("ROW ID"      INTEGER
            PRIMARY KEY,
    "ORDER ID"    VARCHAR2(255),
    "ORDER DATE"  DATE,
    "SHIP DATE"   DATE,
    "SHIP MODE"   VARCHAR2(255),
    "CUSTOMER ID" VARCHAR2(255),
    REGION        VARCHAR2(255),
    "PRODUCT ID"  VARCHAR2(255),
    SALES         FLOAT,
    QUANTITY      INTEGER,
    DISCOUNT      FLOAT,
    PROFIT        FLOAT,
    FOREIGN KEY ("CUSTOMER ID", REGION) REFERENCES "PEOPLE"("CUSTOMER ID",REGION),
    FOREIGN KEY ("PRODUCT ID", REGION) REFERENCES "PRODUCT"("PRODUCT ID",REGION)
);

