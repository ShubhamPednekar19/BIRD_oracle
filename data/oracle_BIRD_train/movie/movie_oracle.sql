CREATE TABLE "ACTOR"
(ACTORID           INTEGER
        CONSTRAINT ACTOR_PK
            PRIMARY KEY,
    NAME              VARCHAR2(255),
    "DATE OF BIRTH"   DATE,
    "BIRTH CITY"      VARCHAR2(255),
    "BIRTH COUNTRY"   VARCHAR2(255),
    "HEIGHT (INCHES)" INTEGER,
    BIOGRAPHY         VARCHAR2(255),
    GENDER            VARCHAR2(255),
    ETHNICITY         VARCHAR2(255),
    NETWORTH          VARCHAR2(255)
);

CREATE TABLE "MOVIE"
(MOVIEID        INTEGER
        CONSTRAINT MOVIE_PK
            PRIMARY KEY,
    TITLE          VARCHAR2(255),
    "MPAA RATING"  VARCHAR2(255),
    BUDGET         INTEGER,
    GROSS          INTEGER,
    "RELEASE DATE" VARCHAR2(255),
    GENRE          VARCHAR2(255),
    RUNTIME        INTEGER,
    RATING         FLOAT,
    "RATING COUNT" INTEGER,
    SUMMARY        VARCHAR2(255)
);

CREATE TABLE "CHARACTERS"
(MOVIEID          INTEGER,
    ACTORID          INTEGER,
    "CHARACTER NAME" VARCHAR2(255),
    CREDITORDER      INTEGER,
    PAY              VARCHAR2(255),
    SCREENTIME       VARCHAR2(255),
    PRIMARY KEY (MOVIEID, ACTORID),
    FOREIGN KEY (ACTORID) REFERENCES "ACTOR"(ACTORID),
    FOREIGN KEY (MOVIEID) REFERENCES "MOVIE"(MOVIEID)
);

