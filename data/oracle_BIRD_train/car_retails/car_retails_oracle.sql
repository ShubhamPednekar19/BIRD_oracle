CREATE TABLE "OFFICES"
(OFFICECODE   VARCHAR2(255)   
        PRIMARY KEY,
    CITY         VARCHAR2(255)   ,
    PHONE        VARCHAR2(255)   ,
    ADDRESSLINE1 VARCHAR2(255)   ,
    ADDRESSLINE2 VARCHAR2(255),
    STATE        VARCHAR2(255),
    COUNTRY      VARCHAR2(255)   ,
    POSTALCODE  VARCHAR2(255)   ,
    TERRITORY    VARCHAR2(255)   
);

CREATE TABLE "EMPLOYEES"
(EMPLOYEENUMBER INTEGER        
        PRIMARY KEY,
    LASTNAME       VARCHAR2(255)    ,
    FIRSTNAME      VARCHAR2(255)    ,
    EXTENSION      VARCHAR2(255)    ,
    EMAIL          VARCHAR2(255)   ,
    OFFICECODE     VARCHAR2(255)    ,
    REPORTSTO      INTEGER,
    JOBTITLE       VARCHAR2(255)    ,
    FOREIGN KEY (OFFICECODE) REFERENCES "OFFICES"(OFFICECODE),
    FOREIGN KEY (REPORTSTO) REFERENCES "EMPLOYEES"(EMPLOYEENUMBER)
);

CREATE TABLE "CUSTOMERS"
(CUSTOMERNUMBER         INTEGER       
        PRIMARY KEY,
    CUSTOMERNAME           VARCHAR2(255)   ,
    CONTACTLASTNAME        VARCHAR2(255)   ,
    CONTACTFIRSTNAME       VARCHAR2(255)   ,
    PHONE                  VARCHAR2(255)   ,
    ADDRESSLINE1           VARCHAR2(255)   ,
    ADDRESSLINE2           VARCHAR2(255),
    CITY                   VARCHAR2(255)   ,
    STATE                  VARCHAR2(255),
    POSTALCODE             VARCHAR2(255),
    COUNTRY                VARCHAR2(255)   ,
    SALESREPEMPLOYEENUMBER INTEGER,
    CREDITLIMIT            FLOAT,
    FOREIGN KEY (SALESREPEMPLOYEENUMBER) REFERENCES "EMPLOYEES"(EMPLOYEENUMBER)
);

CREATE TABLE "ORDERS"
(ORDERNUMBER    INTEGER       
        PRIMARY KEY,
    ORDERDATE      DATE          ,
    REQUIREDDATE   DATE          ,
    SHIPPEDDATE    DATE,
    STATUS         VARCHAR2(255)   ,
    COMMENTS       VARCHAR2(255),
    CUSTOMERNUMBER INTEGER       ,
    FOREIGN KEY (CUSTOMERNUMBER) REFERENCES "CUSTOMERS"(CUSTOMERNUMBER)
);

CREATE TABLE "PAYMENTS"
(CUSTOMERNUMBER INTEGER       ,
    CHECKNUMBER    VARCHAR2(255)   ,
    PAYMENTDATE    DATE          ,
    AMOUNT         FLOAT          ,
    PRIMARY KEY (CUSTOMERNUMBER, CHECKNUMBER),
    FOREIGN KEY (CUSTOMERNUMBER) REFERENCES "CUSTOMERS"(CUSTOMERNUMBER)
);

CREATE TABLE "PRODUCTLINES"
(PRODUCTLINE     VARCHAR2(255)   
        PRIMARY KEY,
    TEXTDESCRIPTION VARCHAR2(255),
    HTMLDESCRIPTION VARCHAR2(255),
    IMAGE           BLOB
);

CREATE TABLE "PRODUCTS"
(PRODUCTCODE        VARCHAR2(255)   
        PRIMARY KEY,
    PRODUCTNAME        VARCHAR2(255)   ,
    PRODUCTLINE        VARCHAR2(255)   ,
    PRODUCTSCALE      VARCHAR2(255)   ,
    PRODUCTVENDOR      VARCHAR2(255)   ,
    PRODUCTDESCRIPTION VARCHAR2(255)          ,
    QUANTITYINSTOCK    INTEGER       ,
    BUYPRICE           FLOAT          ,
    MSRP               FLOAT          ,
    FOREIGN KEY (PRODUCTLINE) REFERENCES "PRODUCTLINES"(PRODUCTLINE)
);

CREATE TABLE "ORDERDETAILS"
(ORDERNUMBER     INTEGER   
        REFERENCES "ORDERS",
    PRODUCTCODE     VARCHAR2(255)      
        REFERENCES "PRODUCTS",
    QUANTITYORDERED INTEGER   ,
    PRICEEACH       FLOAT      ,
    ORDERLINENUMBER INTEGER   ,
    PRIMARY KEY (ORDERNUMBER, PRODUCTCODE)
);

