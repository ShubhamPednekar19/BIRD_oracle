CREATE TABLE "COMMUNITY_AREA"
(COMMUNITY_AREA_NO   INTEGER
            PRIMARY KEY,
    COMMUNITY_AREA_NAME VARCHAR2(255),
    SIDE                VARCHAR2(255),
    POPULATION          VARCHAR2(255)
);

CREATE TABLE "DISTRICT"
(DISTRICT_NO   INTEGER
            PRIMARY KEY,
    DISTRICT_NAME VARCHAR2(255),
    ADDRESS       VARCHAR2(255),
    ZIP_CODE      INTEGER,
    COMMANDER     VARCHAR2(255),
    EMAIL         VARCHAR2(255),
    PHONE         VARCHAR2(255),
    FAX           VARCHAR2(255),
    TTY           VARCHAR2(255),
    TWITTER       VARCHAR2(255)
);

CREATE TABLE "FBI_CODE"
(FBI_CODE_NO   VARCHAR2(255)
            PRIMARY KEY,
    TITLE         VARCHAR2(255),
    DESCRIPTION   VARCHAR2(255),
    CRIME_AGAINST VARCHAR2(255)
);

CREATE TABLE "IUCR"
(IUCR_NO               VARCHAR2(255)
            PRIMARY KEY,
    PRIMARY_DESCRIPTION   VARCHAR2(255),
    SECONDARY_DESCRIPTION VARCHAR2(255),
    INDEX_CODE            VARCHAR2(255)
);

CREATE TABLE "NEIGHBORHOOD"
(NEIGHBORHOOD_NAME VARCHAR2(255)
            PRIMARY KEY,
    COMMUNITY_AREA_NO INTEGER,
    FOREIGN KEY (COMMUNITY_AREA_NO) REFERENCES "COMMUNITY_AREA"(COMMUNITY_AREA_NO)
);

CREATE TABLE "WARD"
(WARD_NO                INTEGER
            PRIMARY KEY,
    ALDERMAN_FIRST_NAME    VARCHAR2(255),
    ALDERMAN_LAST_NAME     VARCHAR2(255),
    ALDERMAN_NAME_SUFFIX   VARCHAR2(255),
    WARD_OFFICE_ADDRESS    VARCHAR2(255),
    WARD_OFFICE_ZIP        VARCHAR2(255),
    WARD_EMAIL             VARCHAR2(255),
    WARD_OFFICE_PHONE      VARCHAR2(255),
    WARD_OFFICE_FAX        VARCHAR2(255),
    CITY_HALL_OFFICE_ROOM  INTEGER,
    CITY_HALL_OFFICE_PHONE VARCHAR2(255),
    CITY_HALL_OFFICE_FAX   VARCHAR2(255),
    POPULATION             INTEGER
);

CREATE TABLE "CRIME"
(REPORT_NO            INTEGER
            PRIMARY KEY,
    CASE_NUMBER          VARCHAR2(255),
    "DATE"                 VARCHAR2(255),
    BLOCK                VARCHAR2(255),
    IUCR_NO              VARCHAR2(255),
    LOCATION_DESCRIPTION VARCHAR2(255),
    ARREST               VARCHAR2(255),
    DOMESTIC             VARCHAR2(255),
    BEAT                 INTEGER,
    DISTRICT_NO          INTEGER,
    WARD_NO              INTEGER,
    COMMUNITY_AREA_NO    INTEGER,
    FBI_CODE_NO          VARCHAR2(255),
    LATITUDE             VARCHAR2(255),
    LONGITUDE            VARCHAR2(255),
    FOREIGN KEY (WARD_NO) REFERENCES "WARD"(WARD_NO),
    FOREIGN KEY (IUCR_NO) REFERENCES "IUCR"(IUCR_NO),
    FOREIGN KEY (DISTRICT_NO) REFERENCES "DISTRICT"(DISTRICT_NO),
    FOREIGN KEY (COMMUNITY_AREA_NO) REFERENCES "COMMUNITY_AREA"(COMMUNITY_AREA_NO),
    FOREIGN KEY (FBI_CODE_NO) REFERENCES "FBI_CODE"(FBI_CODE_NO)
);

