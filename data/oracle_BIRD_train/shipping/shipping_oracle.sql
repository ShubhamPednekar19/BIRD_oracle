CREATE TABLE "CITY"
(CITY_ID    INTEGER
            PRIMARY KEY,
    CITY_NAME  VARCHAR2(255),
    STATE      VARCHAR2(255),
    POPULATION INTEGER,
    AREA       FLOAT
);

CREATE TABLE "CUSTOMER"
(CUST_ID        INTEGER
            PRIMARY KEY,
    CUST_NAME      VARCHAR2(255),
    ANNUAL_REVENUE INTEGER,
    CUST_TYPE      VARCHAR2(255),
    ADDRESS        VARCHAR2(255),
    CITY           VARCHAR2(255),
    STATE          VARCHAR2(255),
    ZIP            FLOAT,
    PHONE          VARCHAR2(255)
);

CREATE TABLE "DRIVER"
(DRIVER_ID  INTEGER
            PRIMARY KEY,
    FIRST_NAME VARCHAR2(255),
    LAST_NAME  VARCHAR2(255),
    ADDRESS    VARCHAR2(255),
    CITY       VARCHAR2(255),
    STATE      VARCHAR2(255),
    ZIP_CODE   INTEGER,
    PHONE      VARCHAR2(255)
);

CREATE TABLE "TRUCK"
(TRUCK_ID   INTEGER
            PRIMARY KEY,
    MAKE       VARCHAR2(255),
    MODEL_YEAR INTEGER
);

CREATE TABLE "SHIPMENT"
(SHIP_ID   INTEGER
            PRIMARY KEY,
    CUST_ID   INTEGER,
    WEIGHT    FLOAT,
    TRUCK_ID  INTEGER,
    DRIVER_ID INTEGER,
    CITY_ID   INTEGER,
    SHIP_DATE VARCHAR2(255),
    FOREIGN KEY (CUST_ID) REFERENCES "CUSTOMER"(CUST_ID),
    FOREIGN KEY (CITY_ID) REFERENCES "CITY"(CITY_ID),
    FOREIGN KEY (DRIVER_ID) REFERENCES "DRIVER"(DRIVER_ID),
    FOREIGN KEY (TRUCK_ID) REFERENCES "TRUCK"(TRUCK_ID)
);

