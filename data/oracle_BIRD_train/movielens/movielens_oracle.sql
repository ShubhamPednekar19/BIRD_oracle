CREATE TABLE "USERS"
(USERID     INTEGER DEFAULT 0   
        PRIMARY KEY,
    AGE        VARCHAR2(255)      ,
    U_GENDER   VARCHAR2(255)      ,
    OCCUPATION VARCHAR2(255)     
);

CREATE TABLE "DIRECTORS"
(DIRECTORID  INTEGER   
        PRIMARY KEY,
    D_QUALITY   INTEGER   ,
    AVG_REVENUE INTEGER   
);

CREATE TABLE "ACTORS"
(ACTORID   INTEGER   
        PRIMARY KEY,
    A_GENDER  VARCHAR2(255)      ,
    A_QUALITY INTEGER   
);

CREATE TABLE "MOVIES"
(MOVIEID     INTEGER DEFAULT 0   
        PRIMARY KEY,
    YEAR        INTEGER             ,
    ISENGLISH   VARCHAR2(255)                ,
    COUNTRY     VARCHAR2(255)                ,
    RUNNINGTIME INTEGER             
);

CREATE TABLE "MOVIES2ACTORS"
(MOVIEID  INTEGER   
        REFERENCES "MOVIES"
              ON DELETE CASCADE,
    ACTORID  INTEGER   
        REFERENCES "ACTORS"
              ON DELETE CASCADE,
    CAST_NUM INTEGER   ,
    PRIMARY KEY (MOVIEID, ACTORID)
);

CREATE TABLE "MOVIES2DIRECTORS"
(MOVIEID    INTEGER   
        REFERENCES "MOVIES"
              ON DELETE CASCADE,
    DIRECTORID INTEGER   
        REFERENCES "DIRECTORS"
              ON DELETE CASCADE,
    GENRE      VARCHAR2(255)      ,
    PRIMARY KEY (MOVIEID, DIRECTORID)
);

CREATE TABLE "U2BASE"
(USERID  INTEGER DEFAULT 0   
        REFERENCES "USERS"
              ON DELETE CASCADE,
    MOVIEID INTEGER             
        REFERENCES "MOVIES"
              ON DELETE CASCADE,
    RATING  VARCHAR2(255)                ,
    PRIMARY KEY (USERID, MOVIEID)
);

