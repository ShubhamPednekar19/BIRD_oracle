CREATE TABLE "AIR_CARRIERS"
(CODE        INTEGER
            PRIMARY KEY,
    DESCRIPTION VARCHAR2(255)
);

CREATE TABLE "AIRPORTS"
(CODE        VARCHAR2(255)
            PRIMARY KEY,
    DESCRIPTION VARCHAR2(255)
);

CREATE TABLE "AIRLINES"
(FL_DATE               VARCHAR2(255),
    OP_CARRIER_AIRLINE_ID INTEGER,
    TAIL_NUM              VARCHAR2(255),
    OP_CARRIER_FL_NUM     INTEGER,
    ORIGIN_AIRPORT_ID     INTEGER,
    ORIGIN_AIRPORT_SEQ_ID INTEGER,
    ORIGIN_CITY_MARKET_ID INTEGER,
    ORIGIN                VARCHAR2(255),
    DEST_AIRPORT_ID       INTEGER,
    DEST_AIRPORT_SEQ_ID   INTEGER,
    DEST_CITY_MARKET_ID   INTEGER,
    DEST                  VARCHAR2(255),
    CRS_DEP_TIME          INTEGER,
    DEP_TIME              INTEGER,
    DEP_DELAY             INTEGER,
    DEP_DELAY_NEW         INTEGER,
    ARR_TIME              INTEGER,
    ARR_DELAY             INTEGER,
    ARR_DELAY_NEW         INTEGER,
    CANCELLED             INTEGER,
    CANCELLATION_CODE     VARCHAR2(255),
    CRS_ELAPSED_TIME      INTEGER,
    ACTUAL_ELAPSED_TIME   INTEGER,
    CARRIER_DELAY         INTEGER,
    WEATHER_DELAY         INTEGER,
    NAS_DELAY             INTEGER,
    SECURITY_DELAY        INTEGER,
    LATE_AIRCRAFT_DELAY   INTEGER,
    FOREIGN KEY (ORIGIN) REFERENCES "AIRPORTS"(CODE),
    FOREIGN KEY (DEST) REFERENCES "AIRPORTS"(CODE),
    FOREIGN KEY (OP_CARRIER_AIRLINE_ID) REFERENCES "AIR_CARRIERS"(CODE)
);

