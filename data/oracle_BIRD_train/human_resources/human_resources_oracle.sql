CREATE TABLE "LOCATION"
(LOCATIONID   INTEGER
        
            PRIMARY KEY,
    LOCATIONCITY VARCHAR2(255),
    ADDRESS      VARCHAR2(255),
    STATE        VARCHAR2(255),
    ZIPCODE      INTEGER,
    OFFICEPHONE  VARCHAR2(255)
);

CREATE TABLE "POSITION"
(POSITIONID        INTEGER
        CONSTRAINT POSITION_PK
            PRIMARY KEY,
    POSITIONTITLE     VARCHAR2(255),
    EDUCATIONREQUIRED VARCHAR2(255),
    MINSALARY         VARCHAR2(255),
    MAXSALARY         VARCHAR2(255)
);

CREATE TABLE "EMPLOYEE"
(SSN         VARCHAR2(255)
            PRIMARY KEY,
    LASTNAME    VARCHAR2(255),
    FIRSTNAME   VARCHAR2(255),
    HIREDATE    VARCHAR2(255),
    SALARY      VARCHAR2(255),
    GENDER      VARCHAR2(255),
    PERFORMANCE VARCHAR2(255),
    POSITIONID  INTEGER,
    LOCATIONID  INTEGER,
    FOREIGN KEY (LOCATIONID) REFERENCES "LOCATION"(LOCATIONID),
    FOREIGN KEY (POSITIONID) REFERENCES "POSITION"(POSITIONID)
);

