CREATE TABLE "CUSTOMERS"
(CUSTOMERID    INTEGER           
        PRIMARY KEY,
    FIRSTNAME     VARCHAR2(255)   ,
    MIDDLEINITIAL VARCHAR2(255) NULL,
    LASTNAME      VARCHAR2(255)   
);

CREATE TABLE "EMPLOYEES"
(EMPLOYEEID    INTEGER           
        PRIMARY KEY,
    FIRSTNAME     VARCHAR2(255)   ,
    MIDDLEINITIAL VARCHAR2(255) NULL,
    LASTNAME      VARCHAR2(255)   
);

CREATE TABLE "PRODUCTS"
(PRODUCTID INTEGER              
        PRIMARY KEY,
    NAME      VARCHAR2(255)      ,
    PRICE     FLOAT NULL
);

CREATE TABLE "SALES"
(SALESID       INTEGER   
        PRIMARY KEY,
    SALESPERSONID INTEGER   ,
    CUSTOMERID    INTEGER   ,
    PRODUCTID     INTEGER   ,
    QUANTITY      INTEGER   ,
    FOREIGN KEY (SALESPERSONID) REFERENCES "EMPLOYEES" (EMPLOYEEID)
              ON DELETE CASCADE,
        FOREIGN KEY (CUSTOMERID) REFERENCES "CUSTOMERS" (CUSTOMERID)
              ON DELETE CASCADE,
        FOREIGN KEY (PRODUCTID) REFERENCES "PRODUCTS" (PRODUCTID)
              ON DELETE CASCADE
);

