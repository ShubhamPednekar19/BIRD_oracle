CREATE TABLE "VOICE_ACTORS"
(CHARACTER     VARCHAR2(255)
            PRIMARY KEY,
    "VOICE_ACTOR" VARCHAR2(255),
    MOVIE         VARCHAR2(255)
);

CREATE TABLE "CHARACTERS"
(MOVIE_TITLE  VARCHAR2(255)
            PRIMARY KEY,
    RELEASE_DATE VARCHAR2(255),
    HERO         VARCHAR2(255),
    VILLIAN      VARCHAR2(255),
    SONG         VARCHAR2(255),
    FOREIGN KEY (HERO) REFERENCES "VOICE_ACTORS"(CHARACTER)
);

CREATE TABLE "DIRECTOR"
(NAME     VARCHAR2(255)
            PRIMARY KEY,
    DIRECTOR VARCHAR2(255),
    FOREIGN KEY (NAME) REFERENCES "CHARACTERS"(MOVIE_TITLE)
);

CREATE TABLE "MOVIES_TOTAL_GROSS"
(MOVIE_TITLE              VARCHAR2(255),
    RELEASE_DATE             VARCHAR2(255),
    GENRE                    VARCHAR2(255),
    MPAA_RATING              VARCHAR2(255),
    TOTAL_GROSS              VARCHAR2(255),
    INFLATION_ADJUSTED_GROSS VARCHAR2(255),
    PRIMARY KEY (MOVIE_TITLE, RELEASE_DATE),
    FOREIGN KEY (MOVIE_TITLE) REFERENCES "CHARACTERS"(MOVIE_TITLE)
);

CREATE TABLE "REVENUE"
(YEAR                              INTEGER
            PRIMARY KEY,
    "STUDIO ENTERTAINMENT[NI 1]"      FLOAT,
    "DISNEY CONSUMER PRODUCTS[NI 2]"  FLOAT,
    "DISNEY INTERACTIVE[NI 3][REV 1]" INTEGER,
    "WALT DISNEY PARKS AND RESORTS"   FLOAT,
    "DISNEY MEDIA NETWORKS"           VARCHAR2(255),
    TOTAL                             INTEGER
);

