CREATE TABLE "EPISODE"
(EPISODE_ID       VARCHAR2(255)
            PRIMARY KEY,
    SERIES           VARCHAR2(255),
    SEASON           INTEGER,
    EPISODE          INTEGER,
    NUMBER_IN_SERIES INTEGER,
    TITLE            VARCHAR2(255),
    SUMMARY          VARCHAR2(255),
    AIR_DATE         DATE,
    EPISODE_IMAGE    VARCHAR2(255),
    RATING           FLOAT,
    VOTES            INTEGER
);

CREATE TABLE "KEYWORD"
(EPISODE_ID VARCHAR2(255),
    KEYWORD    VARCHAR2(255),
    PRIMARY KEY (EPISODE_ID, KEYWORD),
    FOREIGN KEY (EPISODE_ID) REFERENCES "EPISODE"(EPISODE_ID)
);

CREATE TABLE "PERSON"
(PERSON_ID     VARCHAR2(255)
            PRIMARY KEY,
    NAME          VARCHAR2(255),
    BIRTHDATE     DATE,
    BIRTH_NAME    VARCHAR2(255),
    BIRTH_PLACE   VARCHAR2(255),
    BIRTH_REGION  VARCHAR2(255),
    BIRTH_COUNTRY VARCHAR2(255),
    HEIGHT_METERS FLOAT,
    NICKNAME      VARCHAR2(255)
);

CREATE TABLE "AWARD"
(AWARD_ID       INTEGER
            PRIMARY KEY,
    ORGANIZATION   VARCHAR2(255),
    YEAR           INTEGER,
    AWARD_CATEGORY VARCHAR2(255),
    AWARD          VARCHAR2(255),
    SERIES         VARCHAR2(255),
    EPISODE_ID     VARCHAR2(255),
    PERSON_ID      VARCHAR2(255),
    ROLE           VARCHAR2(255),
    RESULT         VARCHAR2(255),
    FOREIGN KEY (EPISODE_ID) REFERENCES "EPISODE"(EPISODE_ID),
    FOREIGN KEY (PERSON_ID) REFERENCES "PERSON"(PERSON_ID)
);

CREATE TABLE "CREDIT"
(EPISODE_ID VARCHAR2(255),
    PERSON_ID  VARCHAR2(255),
    CATEGORY   VARCHAR2(255),
    ROLE       VARCHAR2(255),
    CREDITED   VARCHAR2(255),
    PRIMARY KEY (EPISODE_ID, PERSON_ID),
    FOREIGN KEY (EPISODE_ID) REFERENCES "EPISODE"(EPISODE_ID),
    FOREIGN KEY (PERSON_ID) REFERENCES "PERSON"(PERSON_ID)
);

CREATE TABLE "VOTE"
(EPISODE_ID VARCHAR2(255),
    STARS      INTEGER,
    VOTES      INTEGER,
    PERCENT    FLOAT,
    FOREIGN KEY (EPISODE_ID) REFERENCES "EPISODE"(EPISODE_ID)
);

