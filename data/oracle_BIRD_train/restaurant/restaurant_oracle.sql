CREATE TABLE "GEOGRAPHIC"
(CITY   VARCHAR2(255)   
        PRIMARY KEY,
    COUNTY VARCHAR2(255) NULL,
    REGION VARCHAR2(255) NULL
);

CREATE TABLE "GENERALINFO"
(ID_RESTAURANT INTEGER           
        PRIMARY KEY,
    LABEL         VARCHAR2(255)  NULL,
    FOOD_TYPE     VARCHAR2(255)  NULL,
    CITY          VARCHAR2(255)  NULL,
    REVIEW        FLOAT NULL,
    FOREIGN KEY (CITY) REFERENCES "GEOGRAPHIC"(CITY)
              ON DELETE CASCADE
);

CREATE TABLE "LOCATION"
(ID_RESTAURANT INTEGER          
        PRIMARY KEY,
    STREET_NUM    INTEGER          NULL,
    STREET_NAME   VARCHAR2(255) NULL,
    CITY          VARCHAR2(255) NULL,
    FOREIGN KEY (CITY) REFERENCES "GEOGRAPHIC" (CITY)
              ON DELETE CASCADE,
    FOREIGN KEY (ID_RESTAURANT) REFERENCES "GENERALINFO" (ID_RESTAURANT)
              ON DELETE CASCADE
);

