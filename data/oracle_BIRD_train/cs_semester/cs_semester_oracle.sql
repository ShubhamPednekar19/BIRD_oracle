CREATE TABLE "COURSE"
(COURSE_ID INTEGER
            PRIMARY KEY,
    NAME      VARCHAR2(255),
    CREDIT    INTEGER,
    DIFF      INTEGER
);

CREATE TABLE "PROF"
(PROF_ID         INTEGER          PRIMARY KEY,
    GENDER          VARCHAR2(255),
    FIRST_NAME      VARCHAR2(255),
    LAST_NAME       VARCHAR2(255),
    EMAIL           VARCHAR2(255),
    POPULARITY      INTEGER,
    TEACHINGABILITY INTEGER,
    GRADUATE_FROM   VARCHAR2(255)
);

CREATE TABLE "STUDENT"
(STUDENT_ID   INTEGER
            PRIMARY KEY,
    F_NAME       VARCHAR2(255),
    L_NAME       VARCHAR2(255),
    PHONE_NUMBER VARCHAR2(255),
    EMAIL        VARCHAR2(255),
    INTELLIGENCE INTEGER,
    GPA          FLOAT,
    TYPE         VARCHAR2(255)
);

CREATE TABLE "RA"
(STUDENT_ID INTEGER,
    CAPABILITY INTEGER,
    PROF_ID    INTEGER,
    SALARY     VARCHAR2(255),
    PRIMARY KEY (STUDENT_ID, PROF_ID),
    FOREIGN KEY (PROF_ID) REFERENCES "PROF"(PROF_ID),
    FOREIGN KEY (STUDENT_ID) REFERENCES "STUDENT"(STUDENT_ID)
);

CREATE TABLE "REGISTRATION"
(COURSE_ID  INTEGER,
    STUDENT_ID INTEGER,
    GRADE      VARCHAR2(255),
    SAT        INTEGER,
    PRIMARY KEY (COURSE_ID, STUDENT_ID),
    FOREIGN KEY (COURSE_ID) REFERENCES "COURSE"(COURSE_ID),
    FOREIGN KEY (STUDENT_ID) REFERENCES "STUDENT"(STUDENT_ID)
);

