CREATE TABLE "EMPLOYEE"
(EMPLOYEE_ID INTEGER
            PRIMARY KEY,
    FIRST_NAME  VARCHAR2(255),
    LAST_NAME   VARCHAR2(255),
    ADDRESS     VARCHAR2(255),
    CITY        VARCHAR2(255),
    STATE       VARCHAR2(255),
    ZIP         INTEGER,
    PHONE       VARCHAR2(255),
    TITLE       VARCHAR2(255),
    SALARY      INTEGER,
    SUPERVISOR  INTEGER,
    FOREIGN KEY (SUPERVISOR) REFERENCES "EMPLOYEE"(EMPLOYEE_ID)
);

CREATE TABLE "ESTABLISHMENT"
(LICENSE_NO    INTEGER
            PRIMARY KEY,
    DBA_NAME      VARCHAR2(255),
    AKA_NAME      VARCHAR2(255),
    FACILITY_TYPE VARCHAR2(255),
    RISK_LEVEL    INTEGER,
    ADDRESS       VARCHAR2(255),
    CITY          VARCHAR2(255),
    STATE         VARCHAR2(255),
    ZIP           INTEGER,
    LATITUDE      FLOAT,
    LONGITUDE     FLOAT,
    WARD          INTEGER
);

CREATE TABLE "INSPECTION"
(INSPECTION_ID   INTEGER
            PRIMARY KEY,
    INSPECTION_DATE DATE,
    INSPECTION_TYPE VARCHAR2(255),
    RESULTS         VARCHAR2(255),
    EMPLOYEE_ID     INTEGER,
    LICENSE_NO      INTEGER,
    FOLLOWUP_TO     INTEGER,
    FOREIGN KEY (EMPLOYEE_ID) REFERENCES "EMPLOYEE"(EMPLOYEE_ID),
    FOREIGN KEY (LICENSE_NO) REFERENCES "ESTABLISHMENT"(LICENSE_NO),
    FOREIGN KEY (FOLLOWUP_TO) REFERENCES "INSPECTION"(INSPECTION_ID)
);

CREATE TABLE "INSPECTION_POINT"
(POINT_ID    INTEGER
            PRIMARY KEY,
    DESCRIPTION VARCHAR2(255),
    CATEGORY    VARCHAR2(255),
    CODE        VARCHAR2(255),
    FINE        INTEGER,
    POINT_LEVEL VARCHAR2(255)
);

CREATE TABLE "VIOLATION"
(INSPECTION_ID     INTEGER,
    POINT_ID          INTEGER,
    FINE              INTEGER,
    INSPECTOR_COMMENT VARCHAR2(255),
    PRIMARY KEY (INSPECTION_ID, POINT_ID),
    FOREIGN KEY (INSPECTION_ID) REFERENCES "INSPECTION"(INSPECTION_ID),
    FOREIGN KEY (POINT_ID) REFERENCES "INSPECTION_POINT"(POINT_ID)
);

