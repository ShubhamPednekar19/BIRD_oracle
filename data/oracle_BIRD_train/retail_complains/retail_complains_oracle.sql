CREATE TABLE "STATE"
(STATECODE VARCHAR2(255)        PRIMARY KEY,
    STATE     VARCHAR2(255),
    REGION    VARCHAR2(255)
);

CREATE TABLE "DISTRICT"
(DISTRICT_ID  INTEGER
            PRIMARY KEY,
    CITY         VARCHAR2(255),
    STATE_ABBREV VARCHAR2(255),
    DIVISION     VARCHAR2(255),
    FOREIGN KEY (STATE_ABBREV) REFERENCES "STATE"(STATECODE)
);

CREATE TABLE "CLIENT"
(CLIENT_ID   VARCHAR2(255)
            PRIMARY KEY,
    SEX         VARCHAR2(255),
    DAY         INTEGER,
    MONTH       INTEGER,
    YEAR        INTEGER,
    AGE         INTEGER,
    SOCIAL      VARCHAR2(255),
    FIRST       VARCHAR2(255),
    MIDDLE      VARCHAR2(255),
    LAST        VARCHAR2(255),
    PHONE       VARCHAR2(255),
    EMAIL       VARCHAR2(255),
    ADDRESS_1   VARCHAR2(255),
    ADDRESS_2   VARCHAR2(255),
    CITY        VARCHAR2(255),
    STATE       VARCHAR2(255),
    ZIPCODE     INTEGER,
    DISTRICT_ID INTEGER,
    FOREIGN KEY (DISTRICT_ID) REFERENCES "DISTRICT"(DISTRICT_ID)
);

CREATE TABLE "CALLCENTERLOGS"
("DATE RECEIVED" DATE,
    "COMPLAINT ID"  VARCHAR2(255),
    "RAND CLIENT"   VARCHAR2(255),
    PHONEFINAL      VARCHAR2(255),
    "VRU+LINE"      VARCHAR2(255),
    CALL_ID         INTEGER,
    PRIORITY        INTEGER,
    TYPE            VARCHAR2(255),
    OUTCOME         VARCHAR2(255),
    SERVER          VARCHAR2(255),
    SER_START       VARCHAR2(255),
    SER_EXIT        VARCHAR2(255),
    SER_TIME        VARCHAR2(255),
    PRIMARY KEY ("COMPLAINT ID"),
    FOREIGN KEY ("RAND CLIENT") REFERENCES "CLIENT"(CLIENT_ID)
);

CREATE TABLE "EVENTS"
("DATE RECEIVED"                DATE,
    PRODUCT                        VARCHAR2(255),
    "SUB-PRODUCT"                  VARCHAR2(255),
    ISSUE                          VARCHAR2(255),
    "SUB-ISSUE"                    VARCHAR2(255),
    "CONSUMER COMPLAINT NARRATIVE" VARCHAR2(255),
    TAGS                           VARCHAR2(255),
    "CONSUMER CONSENT PROVIDED?"   VARCHAR2(255),
    "SUBMITTED VIA"                VARCHAR2(255),
    "DATE SENT TO COMPANY"         VARCHAR2(255),
    "COMPANY RESPONSE TO CONSUMER" VARCHAR2(255),
    "TIMELY RESPONSE?"             VARCHAR2(255),
    "CONSUMER DISPUTED?"           VARCHAR2(255),
    "COMPLAINT ID"                 VARCHAR2(255),
    CLIENT_ID                      VARCHAR2(255),
    PRIMARY KEY ("COMPLAINT ID", CLIENT_ID),
    FOREIGN KEY ("COMPLAINT ID") REFERENCES "CALLCENTERLOGS"("COMPLAINT ID"),
    FOREIGN KEY (CLIENT_ID) REFERENCES "CLIENT"(CLIENT_ID)
);

CREATE TABLE "REVIEWS"
("DATE"        DATE
            PRIMARY KEY,
    STARS       INTEGER,
    REVIEWS     VARCHAR2(255),
    PRODUCT     VARCHAR2(255),
    DISTRICT_ID INTEGER,
    FOREIGN KEY (DISTRICT_ID) REFERENCES "DISTRICT"(DISTRICT_ID)
);

