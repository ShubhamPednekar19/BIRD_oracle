CREATE TABLE "RUNS" (RUN_AT VARCHAR2(255)   ,
        MAX_ROWID INTEGER   ,
        REVIEWS_ADDED INTEGER   
    );

CREATE TABLE "PODCASTS" (PODCAST_ID VARCHAR2(255) PRIMARY KEY,
        ITUNES_ID INTEGER   ,
        SLUG VARCHAR2(255)   ,
        ITUNES_URL VARCHAR2(255)   ,
        TITLE VARCHAR2(255)   
    );

CREATE TABLE "REVIEWS"
(PODCAST_ID VARCHAR2(255)      
        CONSTRAINT REVIEWS_PODCASTS_PODCAST_ID_FK
            REFERENCES "PODCASTS",
    TITLE      VARCHAR2(255)      ,
    CONTENT    VARCHAR2(255)      ,
    RATING     INTEGER   ,
    AUTHOR_ID  VARCHAR2(255)      ,
    CREATED_AT VARCHAR2(255)      
);

CREATE TABLE "CATEGORIES"
(PODCAST_ID VARCHAR2(255)   
        CONSTRAINT CATEGORIES_PODCASTS_PODCAST_ID_FK
            REFERENCES "PODCASTS",
    CATEGORY   VARCHAR2(255)   ,
    CONSTRAINT PRIMARY
        PRIMARY KEY (PODCAST_ID, CATEGORY)
);

