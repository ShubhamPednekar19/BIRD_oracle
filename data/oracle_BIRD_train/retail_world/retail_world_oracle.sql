CREATE TABLE "CATEGORIES"
(CATEGORYID INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    CATEGORYNAME VARCHAR2(255),
    DESCRIPTION VARCHAR2(255),
    PICTURE BLOB
);

CREATE TABLE "CUSTOMERS"
(CUSTOMERID INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    CUSTOMERNAME VARCHAR2(255),
    CONTACTNAME VARCHAR2(255),
    CONTACTTITLE VARCHAR2(255),
    ADDRESS VARCHAR2(255),
    CITY VARCHAR2(255),
    REGION VARCHAR2(255),
    POSTALCODE VARCHAR2(255),
    COUNTRY VARCHAR2(255),
    PHONE VARCHAR2(255),
    FAX VARCHAR2(255)
);

CREATE TABLE "EMPLOYEES"
(EMPLOYEEID INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    LASTNAME VARCHAR2(255),
    FIRSTNAME VARCHAR2(255),
    TITLE VARCHAR2(255),
    TITLEOFCOURTESY VARCHAR2(255),
    BIRTHDATE DATE,
    HIREDATE DATE,
    ADDRESS VARCHAR2(255),
    CITY VARCHAR2(255),
    REGION VARCHAR2(255),
    POSTALCODE VARCHAR2(255),
    COUNTRY VARCHAR2(255),
    HOMEPHONE VARCHAR2(255),
    EXTENSION VARCHAR2(255),
    PHOTO VARCHAR2(255),
    NOTES VARCHAR2(255),
    REPORTSTO VARCHAR2(255),
    PHOTOPATH VARCHAR2(255),
    SALARY INTEGER
);

CREATE TABLE "SHIPPERS"(SHIPPERID INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    SHIPPERNAME VARCHAR2(255),
    PHONE VARCHAR2(255)
);

CREATE TABLE "SUPPLIERS"(SUPPLIERID INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    SUPPLIERNAME VARCHAR2(255),
    CONTACTNAME VARCHAR2(255),
    ADDRESS VARCHAR2(255),
    CITY VARCHAR2(255),
    POSTALCODE VARCHAR2(255),
    COUNTRY VARCHAR2(255),
    PHONE VARCHAR2(255)
);

CREATE TABLE "PRODUCTS"(PRODUCTID INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    PRODUCTNAME VARCHAR2(255),
    SUPPLIERID INTEGER,
    CATEGORYID INTEGER,
    UNIT VARCHAR2(255),
    PRICE FLOAT DEFAULT 0,
	FOREIGN KEY (CATEGORYID) REFERENCES "CATEGORIES" (CATEGORYID),
	FOREIGN KEY (SUPPLIERID) REFERENCES "SUPPLIERS" (SUPPLIERID)
);

CREATE TABLE "ORDERS"(ORDERID INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    CUSTOMERID INTEGER,
    EMPLOYEEID INTEGER,
    ORDERDATE TIMESTAMP,
    SHIPPERID INTEGER,
    FOREIGN KEY (EMPLOYEEID) REFERENCES "EMPLOYEES" (EMPLOYEEID),
    FOREIGN KEY (CUSTOMERID) REFERENCES "CUSTOMERS" (CUSTOMERID),
    FOREIGN KEY (SHIPPERID) REFERENCES "SHIPPERS" (SHIPPERID)
);

CREATE TABLE "ORDERDETAILS"(ORDERDETAILID INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ORDERID INTEGER,
    PRODUCTID INTEGER,
    QUANTITY INTEGER,
	FOREIGN KEY (ORDERID) REFERENCES "ORDERS" (ORDERID),
	FOREIGN KEY (PRODUCTID) REFERENCES "PRODUCTS" (PRODUCTID)
);

