CREATE TABLE "APP_ALL"
(APP_ID INTEGER NOT NULL  ,
    PRIMARY KEY (APP_ID)
);

CREATE TABLE "GENDER_AGE_TEST" (DEVICE_ID INTEGER NOT NULL  ,
  PRIMARY KEY (DEVICE_ID)
);

CREATE TABLE "GENDER_AGE_TRAIN" (DEVICE_ID INTEGER NOT NULL  ,
  GENDER VARCHAR2(255) DEFAULT NULL,
  AGE INTEGER DEFAULT NULL,
  "GROUP" VARCHAR2(255) DEFAULT NULL,
  PRIMARY KEY (DEVICE_ID)
);

CREATE TABLE "LABEL_CATEGORIES" (LABEL_ID INTEGER NOT NULL  ,
  CATEGORY VARCHAR2(255) DEFAULT NULL,
  PRIMARY KEY (LABEL_ID)
);

CREATE TABLE "PHONE_BRAND_DEVICE_MODEL2" (DEVICE_ID INTEGER NOT NULL PRIMARY KEY,
  PHONE_BRAND VARCHAR2(255) NOT NULL  ,
  DEVICE_MODEL VARCHAR2(255) NOT NULL
);

CREATE TABLE "SAMPLE_SUBMISSION" (DEVICE_ID INTEGER NOT NULL  ,
  "F23-" FLOAT DEFAULT NULL,
  "F24-26" FLOAT DEFAULT NULL,
  "F27-28" FLOAT DEFAULT NULL,
  "F29-32" FLOAT DEFAULT NULL,
  "F33-42" FLOAT DEFAULT NULL,
  "F43+" FLOAT DEFAULT NULL,
  "M22-" FLOAT DEFAULT NULL,
  "M23-26" FLOAT DEFAULT NULL,
  "M27-28" FLOAT DEFAULT NULL,
  "M29-31" FLOAT DEFAULT NULL,
  "M32-38" FLOAT DEFAULT NULL,
  "M39+" FLOAT DEFAULT NULL,
  PRIMARY KEY (DEVICE_ID)
);

CREATE TABLE "EVENTS" (EVENT_ID INTEGER NOT NULL  ,
  DEVICE_ID INTEGER DEFAULT NULL,
  TIMESTAMP TIMESTAMP DEFAULT NULL,
  LONGITUDE FLOAT DEFAULT NULL,
  LATITUDE FLOAT DEFAULT NULL,
  PRIMARY KEY (EVENT_ID)
);

CREATE TABLE "APP_EVENTS" (EVENT_ID INTEGER NOT NULL  ,
  APP_ID INTEGER NOT NULL  ,
  IS_INSTALLED INTEGER NOT NULL  ,
  IS_ACTIVE INTEGER NOT NULL  ,
  PRIMARY KEY (EVENT_ID,APP_ID),
  FOREIGN KEY (EVENT_ID) REFERENCES "EVENTS" (EVENT_ID) ON DELETE CASCADE  
);

CREATE TABLE "APP_LABELS" (APP_ID INTEGER NOT NULL  ,
  LABEL_ID INTEGER NOT NULL  ,
  FOREIGN KEY (LABEL_ID) REFERENCES "LABEL_CATEGORIES" (LABEL_ID) ON DELETE CASCADE  ,
  FOREIGN KEY (APP_ID) REFERENCES "APP_ALL" (APP_ID) ON DELETE CASCADE  
);

CREATE TABLE "GENDER_AGE" (DEVICE_ID INTEGER NOT NULL  ,
  GENDER VARCHAR2(255) DEFAULT NULL,
  AGE INTEGER DEFAULT NULL,
  "GROUP" VARCHAR2(255) DEFAULT NULL,
  PRIMARY KEY (DEVICE_ID),
  FOREIGN KEY (DEVICE_ID) REFERENCES "PHONE_BRAND_DEVICE_MODEL2" (DEVICE_ID) ON DELETE CASCADE  
);

CREATE TABLE "EVENTS_RELEVANT" (EVENT_ID INTEGER NOT NULL  ,
  DEVICE_ID INTEGER DEFAULT NULL,
  TIMESTAMP TIMESTAMP NOT NULL  ,
  LONGITUDE FLOAT NOT NULL  ,
  LATITUDE FLOAT NOT NULL  ,
  PRIMARY KEY (EVENT_ID),
  FOREIGN KEY (DEVICE_ID) REFERENCES "GENDER_AGE" (DEVICE_ID) ON DELETE CASCADE  
);

CREATE TABLE "APP_EVENTS_RELEVANT" (EVENT_ID INTEGER NOT NULL  ,
  APP_ID INTEGER NOT NULL  ,
  IS_INSTALLED INTEGER DEFAULT NULL,
  IS_ACTIVE INTEGER DEFAULT NULL,
  PRIMARY KEY (EVENT_ID,APP_ID),
  FOREIGN KEY (EVENT_ID) REFERENCES "EVENTS_RELEVANT" (EVENT_ID) ON DELETE CASCADE  ,
  FOREIGN KEY (APP_ID) REFERENCES "APP_ALL" (APP_ID) ON DELETE CASCADE  
);

