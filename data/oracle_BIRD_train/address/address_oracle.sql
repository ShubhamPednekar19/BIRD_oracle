CREATE TABLE "CBSA"
(CBSA      INTEGER
            PRIMARY KEY,
    CBSA_NAME VARCHAR2(255),
    CBSA_TYPE VARCHAR2(255)
);

CREATE TABLE "STATE"
(ABBREVIATION VARCHAR2(255)
            PRIMARY KEY,
    "NAME"         VARCHAR2(255)
);

CREATE TABLE "CONGRESS"
(COGNRESS_REP_ID VARCHAR2(255)
            PRIMARY KEY,
    FIRST_NAME      VARCHAR2(255),
    LAST_NAME       VARCHAR2(255),
    CID             VARCHAR2(255),
    PARTY           VARCHAR2(255),
    STATE           VARCHAR2(255),
    ABBREVIATION    VARCHAR2(255),
    HOUSE           VARCHAR2(255),
    DISTRICT        INTEGER,
    LAND_AREA       FLOAT,
    FOREIGN KEY (ABBREVIATION) REFERENCES "STATE"(ABBREVIATION)
);

CREATE TABLE "ZIP_DATA"
(ZIP_CODE                         INTEGER
            PRIMARY KEY,
    CITY                             VARCHAR2(255),
    STATE                            VARCHAR2(255),
    MULTI_COUNTY                     VARCHAR2(255),
    "TYPE"                             VARCHAR2(255),
    ORGANIZATION                     VARCHAR2(255),
    TIME_ZONE                        VARCHAR2(255),
    DAYLIGHT_SAVINGS                 VARCHAR2(255),
    LATITUDE                         FLOAT,
    LONGITUDE                        FLOAT,
    ELEVATION                        INTEGER,
    STATE_FIPS                       INTEGER,
    COUNTY_FIPS                      INTEGER,
    REGION                           VARCHAR2(255),
    DIVISION                         VARCHAR2(255),
    POPULATION_2020                  INTEGER,
    POPULATION_2010                  INTEGER,
    HOUSEHOLDS                       INTEGER,
    AVG_HOUSE_VALUE                  INTEGER,
    AVG_INCOME_PER_HOUSEHOLD         INTEGER,
    PERSONS_PER_HOUSEHOLD            FLOAT,
    WHITE_POPULATION                 INTEGER,
    BLACK_POPULATION                 INTEGER,
    HISPANIC_POPULATION              INTEGER,
    ASIAN_POPULATION                 INTEGER,
    AMERICAN_INDIAN_POPULATION       INTEGER,
    HAWAIIAN_POPULATION              INTEGER,
    OTHER_POPULATION                 INTEGER,
    MALE_POPULATION                  INTEGER,
    FEMALE_POPULATION                INTEGER,
    MEDIAN_AGE                       FLOAT,
    MALE_MEDIAN_AGE                  FLOAT,
    FEMALE_MEDIAN_AGE                FLOAT,
    RESIDENTIAL_MAILBOXES            INTEGER,
    BUSINESS_MAILBOXES               INTEGER,
    TOTAL_DELIVERY_RECEPTACLES       INTEGER,
    BUSINESSES                       INTEGER,
    "1ST_QUARTER_PAYROLL"            INTEGER,
    ANNUAL_PAYROLL                   INTEGER,
    EMPLOYEES                        INTEGER,
    WATER_AREA                       FLOAT,
    LAND_AREA                        FLOAT,
    SINGLE_FAMILY_DELIVERY_UNITS     INTEGER,
    MULTI_FAMILY_DELIVERY_UNITS      INTEGER,
    TOTAL_BENEFICIARIES              INTEGER,
    RETIRED_WORKERS                  INTEGER,
    DISABLED_WORKERS                 INTEGER,
    PARENTS_AND_WIDOWED              INTEGER,
    SPOUSES                          INTEGER,
    CHILDREN                         INTEGER,
    OVER_65                          INTEGER,
    MONTHLY_BENEFITS_ALL             INTEGER,
    MONTHLY_BENEFITS_RETIRED_WORKERS INTEGER,
    MONTHLY_BENEFITS_WIDOWED         INTEGER,
    CBSA                             INTEGER,
    FOREIGN KEY (STATE) REFERENCES "STATE"(ABBREVIATION),
    FOREIGN KEY (CBSA) REFERENCES "CBSA"(CBSA)
);

CREATE TABLE "ALIAS"
(ZIP_CODE INTEGER
            PRIMARY KEY,
    ALIAS    VARCHAR2(255),
    FOREIGN KEY (ZIP_CODE) REFERENCES "ZIP_DATA"(ZIP_CODE)
);

CREATE TABLE "AREA_CODE"
(ZIP_CODE  INTEGER,
    AREA_CODE INTEGER,
    PRIMARY KEY (ZIP_CODE, AREA_CODE),
    FOREIGN KEY (ZIP_CODE) REFERENCES "ZIP_DATA"(ZIP_CODE)
);

CREATE TABLE "AVOID"
(ZIP_CODE  INTEGER,
    BAD_ALIAS VARCHAR2(255),
    PRIMARY KEY (ZIP_CODE, BAD_ALIAS),
    FOREIGN KEY (ZIP_CODE) REFERENCES "ZIP_DATA"(ZIP_CODE)
);

CREATE TABLE "COUNTRY"
(ZIP_CODE INTEGER,
    COUNTY   VARCHAR2(255),
    STATE    VARCHAR2(255),
    PRIMARY KEY (ZIP_CODE, COUNTY),
    FOREIGN KEY (ZIP_CODE) REFERENCES "ZIP_DATA"(ZIP_CODE),
    FOREIGN KEY (STATE) REFERENCES "STATE"(ABBREVIATION)
);

CREATE TABLE "ZIP_CONGRESS"
(ZIP_CODE INTEGER,
    DISTRICT VARCHAR2(255),
    PRIMARY KEY (ZIP_CODE, DISTRICT),
    FOREIGN KEY (DISTRICT) REFERENCES "CONGRESS"(COGNRESS_REP_ID),
    FOREIGN KEY (ZIP_CODE) REFERENCES "ZIP_DATA"(ZIP_CODE)
);

