CREATE TABLE "COURSE"
(COURSE_ID   INTEGER
            PRIMARY KEY,
    COURSELEVEL VARCHAR2(255)
);

CREATE TABLE "PERSON"
(P_ID           INTEGER
        CONSTRAINT PERSON_PK
            PRIMARY KEY,
    PROFESSOR      INTEGER,
    STUDENT        INTEGER,
    HASPOSITION    VARCHAR2(255),
    INPHASE        VARCHAR2(255),
    YEARSINPROGRAM VARCHAR2(255)
);

CREATE TABLE "ADVISEDBY"
(P_ID       INTEGER,
    P_ID_DUMMY INTEGER,
    CONSTRAINT ADVISEDBY_PK
        PRIMARY KEY (P_ID, P_ID_DUMMY),
    CONSTRAINT ADVISEDBY_PERSON_P_ID_P_ID_FK
        FOREIGN KEY (P_ID) REFERENCES "PERSON" (P_ID)
);

CREATE TABLE "TAUGHTBY"
(COURSE_ID INTEGER,
    P_ID      INTEGER,
    PRIMARY KEY (COURSE_ID, P_ID),
    FOREIGN KEY (P_ID) REFERENCES "PERSON"(P_ID),
    FOREIGN KEY (COURSE_ID) REFERENCES "COURSE"(COURSE_ID)
);

