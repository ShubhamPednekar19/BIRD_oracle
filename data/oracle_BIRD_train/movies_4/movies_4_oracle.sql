CREATE TABLE "COUNTRY"
(COUNTRY_ID       INTEGER   
            PRIMARY KEY,
    COUNTRY_ISO_CODE VARCHAR2(255)  DEFAULT NULL,
    COUNTRY_NAME     VARCHAR2(255) DEFAULT NULL
);

CREATE TABLE "DEPARTMENT"
(DEPARTMENT_ID   INTEGER   
            PRIMARY KEY,
    DEPARTMENT_NAME VARCHAR2(255) DEFAULT NULL
);

CREATE TABLE "GENDER"
(GENDER_ID INTEGER   
            PRIMARY KEY,
    GENDER    VARCHAR2(255) DEFAULT NULL
);

CREATE TABLE "GENRE"
(GENRE_ID   INTEGER   
            PRIMARY KEY,
    GENRE_NAME VARCHAR2(255) DEFAULT NULL
);

CREATE TABLE "KEYWORD"
(KEYWORD_ID   INTEGER   
            PRIMARY KEY,
    KEYWORD_NAME VARCHAR2(255) DEFAULT NULL
);

CREATE TABLE "LANGUAGE"
(LANGUAGE_ID   INTEGER   
            PRIMARY KEY,
    LANGUAGE_CODE VARCHAR2(255)  DEFAULT NULL,
    LANGUAGE_NAME VARCHAR2(255) DEFAULT NULL
);

CREATE TABLE "LANGUAGE_ROLE"
(ROLE_ID       INTEGER   
            PRIMARY KEY,
    LANGUAGE_ROLE VARCHAR2(255) DEFAULT NULL
);

CREATE TABLE "MOVIE"
(MOVIE_ID    INTEGER   
            PRIMARY KEY,
    TITLE        VARCHAR2(255)  DEFAULT NULL,
    BUDGET       INTEGER            DEFAULT NULL,
    HOMEPAGE     VARCHAR2(255)  DEFAULT NULL,
    OVERVIEW     VARCHAR2(255)  DEFAULT NULL,
    POPULARITY   FLOAT DEFAULT NULL,
    RELEASE_DATE DATE           DEFAULT NULL,
    REVENUE      INTEGER     DEFAULT NULL,
    RUNTIME      INTEGER           DEFAULT NULL,
    MOVIE_STATUS VARCHAR2(255)    DEFAULT NULL,
    TAGLINE      VARCHAR2(255)  DEFAULT NULL,
    VOTE_AVERAGE FLOAT  DEFAULT NULL,
    VOTE_COUNT   INTEGER            DEFAULT NULL
);

CREATE TABLE "MOVIE_GENRES"
(MOVIE_ID INTEGER DEFAULT NULL,
    GENRE_ID INTEGER DEFAULT NULL,
    FOREIGN KEY (GENRE_ID) REFERENCES "GENRE"(GENRE_ID),
    FOREIGN KEY (MOVIE_ID) REFERENCES "MOVIE"(MOVIE_ID)
);

CREATE TABLE "MOVIE_LANGUAGES"
(MOVIE_ID         INTEGER DEFAULT NULL,
    LANGUAGE_ID      INTEGER DEFAULT NULL,
    LANGUAGE_ROLE_ID INTEGER DEFAULT NULL,
    FOREIGN KEY (LANGUAGE_ID) REFERENCES "LANGUAGE"(LANGUAGE_ID),
    FOREIGN KEY (MOVIE_ID) REFERENCES "MOVIE"(MOVIE_ID),
    FOREIGN KEY (LANGUAGE_ROLE_ID) REFERENCES "LANGUAGE_ROLE"(ROLE_ID)
);

CREATE TABLE "PERSON"
(PERSON_ID   INTEGER   
            PRIMARY KEY,
    PERSON_NAME VARCHAR2(255) DEFAULT NULL
);

CREATE TABLE "MOVIE_CREW"
(MOVIE_ID      INTEGER          DEFAULT NULL,
    PERSON_ID     INTEGER          DEFAULT NULL,
    DEPARTMENT_ID INTEGER          DEFAULT NULL,
    JOB           VARCHAR2(255) DEFAULT NULL,
    FOREIGN KEY (DEPARTMENT_ID) REFERENCES "DEPARTMENT"(DEPARTMENT_ID),
    FOREIGN KEY (MOVIE_ID) REFERENCES "MOVIE"(MOVIE_ID),
    FOREIGN KEY (PERSON_ID) REFERENCES "PERSON"(PERSON_ID)
);

CREATE TABLE "PRODUCTION_COMPANY"
(COMPANY_ID   INTEGER   
            PRIMARY KEY,
    COMPANY_NAME VARCHAR2(255) DEFAULT NULL
);

CREATE TABLE "PRODUCTION_COUNTRY"
(MOVIE_ID   INTEGER DEFAULT NULL,
    COUNTRY_ID INTEGER DEFAULT NULL,
    FOREIGN KEY (COUNTRY_ID) REFERENCES "COUNTRY"(COUNTRY_ID),
    FOREIGN KEY (MOVIE_ID) REFERENCES "MOVIE"(MOVIE_ID)
);

CREATE TABLE "MOVIE_CAST"
(MOVIE_ID       INTEGER          DEFAULT NULL,
    PERSON_ID      INTEGER          DEFAULT NULL,
    CHARACTER_NAME VARCHAR2(255) DEFAULT NULL,
    GENDER_ID      INTEGER          DEFAULT NULL,
    CAST_ORDER     INTEGER       DEFAULT NULL,
    FOREIGN KEY (GENDER_ID) REFERENCES "GENDER"(GENDER_ID),
    FOREIGN KEY (MOVIE_ID) REFERENCES "MOVIE"(MOVIE_ID),
    FOREIGN KEY (PERSON_ID) REFERENCES "PERSON"(PERSON_ID)
);

CREATE TABLE "MOVIE_KEYWORDS"
(MOVIE_ID   INTEGER DEFAULT NULL
        REFERENCES "MOVIE",
    KEYWORD_ID INTEGER DEFAULT NULL
        REFERENCES "KEYWORD"
);

CREATE TABLE "MOVIE_COMPANY"
(MOVIE_ID   INTEGER DEFAULT NULL
        REFERENCES "MOVIE",
    COMPANY_ID INTEGER DEFAULT NULL
        REFERENCES "PRODUCTION_COMPANY"
);

