CREATE TABLE "COUNTRY" (CODE VARCHAR2(255)    DEFAULT '',
  NAME VARCHAR2(255)    DEFAULT '',
  CONTINENT VARCHAR2(255)    DEFAULT 'ASIA',
  REGION VARCHAR2(255)    DEFAULT '',
  SURFACEAREA FLOAT    DEFAULT 0.00,
  INDEPYEAR INTEGER DEFAULT NULL,
  POPULATION INTEGER    DEFAULT 0,
  LIFEEXPECTANCY FLOAT DEFAULT NULL,
  GNP FLOAT DEFAULT NULL,
  GNPOLD FLOAT DEFAULT NULL,
  LOCALNAME VARCHAR2(255)    DEFAULT '',
  GOVERNMENTFORM VARCHAR2(255)    DEFAULT '',
  HEADOFSTATE VARCHAR2(255) DEFAULT NULL,
  CAPITAL INTEGER DEFAULT NULL,
  CODE2 VARCHAR2(255)    DEFAULT '',
  PRIMARY KEY (CODE)
);

CREATE TABLE "CITY" (ID INTEGER    GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  NAME VARCHAR2(255)    DEFAULT '',
  COUNTRYCODE VARCHAR2(255)    DEFAULT '',
  DISTRICT VARCHAR2(255)    DEFAULT '',
  POPULATION INTEGER    DEFAULT 0,
  FOREIGN KEY (COUNTRYCODE) REFERENCES "COUNTRY" (CODE)
);

CREATE TABLE "COUNTRYLANGUAGE" (COUNTRYCODE VARCHAR2(255)    DEFAULT '',
  LANGUAGE VARCHAR2(255)    DEFAULT '',
  ISOFFICIAL  VARCHAR2(255)  DEFAULT 'F',
  PERCENTAGE FLOAT    DEFAULT 0.0,
  PRIMARY KEY (COUNTRYCODE,LANGUAGE),
  FOREIGN KEY (COUNTRYCODE) REFERENCES "COUNTRY" (CODE)
);

