CREATE TABLE "INGREDIENT"
(INGREDIENT_ID INTEGER
            PRIMARY KEY,
    CATEGORY      VARCHAR2(255),
    NAME          VARCHAR2(255),
    PLURAL        VARCHAR2(255)
);

CREATE TABLE "RECIPE"
(RECIPE_ID  INTEGER
            PRIMARY KEY,
    TITLE      VARCHAR2(255),
    SUBTITLE   VARCHAR2(255),
    SERVINGS   INTEGER,
    YIELD_UNIT VARCHAR2(255),
    PREP_MIN   INTEGER,
    COOK_MIN   INTEGER,
    STND_MIN   INTEGER,
    SOURCE     VARCHAR2(255),
    INTRO      VARCHAR2(255),
    DIRECTIONS VARCHAR2(255)
);

CREATE TABLE "NUTRITION"
(RECIPE_ID     INTEGER
            PRIMARY KEY,
    PROTEIN       FLOAT,
    CARBO         FLOAT,
    ALCOHOL       FLOAT,
    TOTAL_FAT     FLOAT,
    SAT_FAT       FLOAT,
    CHOLESTRL     FLOAT,
    SODIUM        FLOAT,
    IRON          FLOAT,
    VITAMIN_C     FLOAT,
    VITAMIN_A     FLOAT,
    FIBER         FLOAT,
    PCNT_CAL_CARB FLOAT,
    PCNT_CAL_FAT  FLOAT,
    PCNT_CAL_PROT FLOAT,
    CALORIES      FLOAT,
    FOREIGN KEY (RECIPE_ID) REFERENCES "RECIPE"(RECIPE_ID)
);

CREATE TABLE "QUANTITY"
(QUANTITY_ID   INTEGER
            PRIMARY KEY,
    RECIPE_ID     INTEGER,
    INGREDIENT_ID INTEGER,
    MAX_QTY       FLOAT,
    MIN_QTY       FLOAT,
    UNIT          VARCHAR2(255),
    PREPARATION   VARCHAR2(255),
    OPTIONAL      VARCHAR2(255),
    FOREIGN KEY (RECIPE_ID) REFERENCES "RECIPE"(RECIPE_ID),
    FOREIGN KEY (INGREDIENT_ID) REFERENCES "INGREDIENT"(INGREDIENT_ID),
    FOREIGN KEY (RECIPE_ID) REFERENCES "NUTRITION"(RECIPE_ID)
);

