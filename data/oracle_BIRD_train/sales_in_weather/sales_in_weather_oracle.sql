CREATE TABLE "SALES_IN_WEATHER"
("DATE"      DATE,
    STORE_NBR INTEGER PRIMARY KEY,
    ITEM_NBR  INTEGER,
    UNITS     INTEGER
);

CREATE TABLE "WEATHER"
(STATION_NBR INTEGER PRIMARY KEY,
    "DATE"        DATE,
    TMAX        INTEGER,
    TMIN        INTEGER,
    TAVG        INTEGER,
    DEPART      INTEGER,
    DEWPOINT    INTEGER,
    WETBULB     INTEGER,
    HEAT        INTEGER,
    COOL        INTEGER,
    SUNRISE     VARCHAR2(255),
    SUNSET      VARCHAR2(255),
    CODESUM     VARCHAR2(255),
    SNOWFALL    FLOAT,
    PRECIPTOTAL FLOAT,
    STNPRESSURE FLOAT,
    SEALEVEL    FLOAT,
    RESULTSPEED FLOAT,
    RESULTDIR   INTEGER,
    AVGSPEED    FLOAT
);

CREATE TABLE "RELATION"
(STORE_NBR   INTEGER
            PRIMARY KEY,
    STATION_NBR INTEGER,
    FOREIGN KEY (STORE_NBR) REFERENCES "SALES_IN_WEATHER"(STORE_NBR),
    FOREIGN KEY (STATION_NBR) REFERENCES "WEATHER"(STATION_NBR)
);

