CREATE TABLE "CUSTOMERS"
(CUSTOMERID       INTEGER        PRIMARY KEY,
    "CUSTOMER NAMES" VARCHAR2(255)
);

CREATE TABLE "PRODUCTS"
(PRODUCTID      INTEGER        PRIMARY KEY,
    "PRODUCT NAME" VARCHAR2(255)
);

CREATE TABLE "REGIONS"
(STATECODE VARCHAR2(255)
            PRIMARY KEY,
    STATE     VARCHAR2(255),
    REGION    VARCHAR2(255)
);

CREATE TABLE "SALES_TEAM" (SALESTEAMID INTEGER PRIMARY KEY,  "SALES TEAM" VARCHAR2(255), REGION VARCHAR2(255));

CREATE TABLE "STORE_LOCATIONS" (STOREID INTEGER PRIMARY KEY,  "CITY NAME" VARCHAR2(255), COUNTY VARCHAR2(255), STATECODE VARCHAR2(255) REFERENCES "REGIONS" (STATECODE), "STATE" VARCHAR2(255), "TYPE" VARCHAR2(255), LATITUDE FLOAT, LONGITUDE FLOAT, AREACODE INTEGER, POPULATION INTEGER,  "HOUSEHOLD INCOME" INTEGER,  "MEDIAN INCOME" INTEGER,  "LAND AREA" INTEGER,  "WATER AREA" INTEGER,  "TIME ZONE" VARCHAR2(255));

CREATE TABLE "SALES_ORDERS" (ORDERNUMBER VARCHAR2(255)  PRIMARY KEY,  "SALES CHANNEL" VARCHAR2(255), WAREHOUSECODE VARCHAR2(255), PROCUREDDATE VARCHAR2(255), ORDERDATE VARCHAR2(255), SHIPDATE VARCHAR2(255), DELIVERYDATE VARCHAR2(255), CURRENCYCODE VARCHAR2(255), SALESTEAMID INTEGER  REFERENCES "SALES_TEAM" (SALESTEAMID), CUSTOMERID INTEGER REFERENCES "CUSTOMERS" (CUSTOMERID), STOREID INTEGER  REFERENCES "STORE_LOCATIONS" (STOREID), PRODUCTID INTEGER REFERENCES "PRODUCTS" (PRODUCTID),  "ORDER QUANTITY" INTEGER,  "DISCOUNT APPLIED" FLOAT,  "UNIT PRICE" VARCHAR2(255),  "UNIT COST" VARCHAR2(255));

