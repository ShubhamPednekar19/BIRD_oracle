CREATE TABLE "TORRENTS"
(GROUPNAME     VARCHAR2(255),
    TOTALSNATCHED INTEGER,
    ARTIST        VARCHAR2(255),
    GROUPYEAR     INTEGER,
    RELEASETYPE   VARCHAR2(255),
    GROUPID       INTEGER,
    ID            INTEGER
        CONSTRAINT TORRENTS_PK
            PRIMARY KEY
);

CREATE TABLE "TAGS"
("INDEX" INTEGER
        CONSTRAINT TAGS_PK
            PRIMARY KEY,
    ID      INTEGER
        CONSTRAINT TAGS_TORRENTS_ID_FK
            REFERENCES "TORRENTS",
    TAG     VARCHAR2(255)
);

