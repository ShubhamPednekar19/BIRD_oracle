CREATE TABLE "DISH"
(ID             INTEGER
            PRIMARY KEY,
    NAME           VARCHAR2(255),
    DESCRIPTION    VARCHAR2(255),
    MENUS_APPEARED INTEGER,
    TIMES_APPEARED INTEGER,
    FIRST_APPEARED INTEGER,
    LAST_APPEARED  INTEGER,
    LOWEST_PRICE   FLOAT,
    HIGHEST_PRICE  FLOAT
);

CREATE TABLE "MENU"
(ID                   INTEGER
            PRIMARY KEY,
    NAME                 VARCHAR2(255),
    SPONSOR              VARCHAR2(255),
    EVENT                VARCHAR2(255),
    VENUE                VARCHAR2(255),
    PLACE                VARCHAR2(255),
    PHYSICAL_DESCRIPTION VARCHAR2(255),
    OCCASION             VARCHAR2(255),
    NOTES                VARCHAR2(255),
    CALL_NUMBER          VARCHAR2(255),
    KEYWORDS             VARCHAR2(255),
    LANGUAGE             VARCHAR2(255),
    "DATE"                 DATE,
    LOCATION             VARCHAR2(255),
    LOCATION_TYPE        VARCHAR2(255),
    CURRENCY             VARCHAR2(255),
    CURRENCY_SYMBOL      VARCHAR2(255),
    STATUS               VARCHAR2(255),
    PAGE_COUNT           INTEGER,
    DISH_COUNT           INTEGER
);

CREATE TABLE "MENUPAGE"
(ID          INTEGER
            PRIMARY KEY,
    MENU_ID     INTEGER,
    PAGE_NUMBER INTEGER,
    IMAGE_ID    FLOAT,
    FULL_HEIGHT INTEGER,
    FULL_WIDTH  INTEGER,
    UUID        VARCHAR2(255),
    FOREIGN KEY (MENU_ID) REFERENCES "MENU"(ID)
);

CREATE TABLE "MENUITEM"
(ID           INTEGER
            PRIMARY KEY,
    MENU_PAGE_ID INTEGER,
    PRICE        FLOAT,
    HIGH_PRICE   FLOAT,
    DISH_ID      INTEGER,
    CREATED_AT   VARCHAR2(255),
    UPDATED_AT   VARCHAR2(255),
    XPOS         FLOAT,
    YPOS         FLOAT,
    FOREIGN KEY (DISH_ID) REFERENCES "DISH"(ID),
    FOREIGN KEY (MENU_PAGE_ID) REFERENCES "MENUPAGE"(ID)
);

