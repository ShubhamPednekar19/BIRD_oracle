CREATE TABLE "CLASSIFICATION"
(GENEID       VARCHAR2(255)     
        PRIMARY KEY,
    LOCALIZATION VARCHAR2(255)   
);

CREATE TABLE "GENES"
(GENEID       VARCHAR2(255)     ,
    ESSENTIAL    VARCHAR2(255)   ,
    CLASS        VARCHAR2(255)   ,
    COMPLEX      VARCHAR2(255) NULL,
    PHENOTYPE    VARCHAR2(255)   ,
    MOTIF        VARCHAR2(255)   ,
    CHROMOSOME   INTEGER            ,
    FUNCTION     VARCHAR2(255)   ,
    LOCALIZATION VARCHAR2(255)   ,
    FOREIGN KEY (GENEID) REFERENCES "CLASSIFICATION" (GENEID)
              ON DELETE CASCADE
);

CREATE TABLE "INTERACTIONS"
(GENEID1         VARCHAR2(255)       ,
    GENEID2         VARCHAR2(255)        ,
    TYPE            VARCHAR2(255)      ,
    EXPRESSION_CORR FLOAT   ,
    PRIMARY KEY (GENEID1, GENEID2),
    FOREIGN KEY (GENEID1) REFERENCES "CLASSIFICATION" (GENEID)
              ON DELETE CASCADE,
    FOREIGN KEY (GENEID2) REFERENCES "CLASSIFICATION" (GENEID)
              ON DELETE CASCADE
);

