CREATE TABLE "TRAINS" (ID INTEGER   ,
  DIRECTION VARCHAR2(255) DEFAULT NULL,
  PRIMARY KEY (ID)
);

CREATE TABLE "CARS" (ID INTEGER   ,
  TRAIN_ID INTEGER DEFAULT NULL,
  POSITION INTEGER DEFAULT NULL,
  SHAPE VARCHAR2(255) DEFAULT NULL,
  LEN VARCHAR2(255) DEFAULT NULL,
  SIDES VARCHAR2(255) DEFAULT NULL,
  ROOF VARCHAR2(255) DEFAULT NULL,
  WHEELS INTEGER DEFAULT NULL,
  LOAD_SHAPE VARCHAR2(255) DEFAULT NULL,
  LOAD_NUM INTEGER DEFAULT NULL,
  PRIMARY KEY (ID),
  FOREIGN KEY (TRAIN_ID) REFERENCES "TRAINS" (ID) ON DELETE CASCADE  
);

