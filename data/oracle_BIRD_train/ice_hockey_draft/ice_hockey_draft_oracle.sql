CREATE TABLE "HEIGHT_INFO"
(HEIGHT_ID      INTEGER
            PRIMARY KEY,
    HEIGHT_IN_CM   INTEGER,
    HEIGHT_IN_INCH VARCHAR2(255)
);

CREATE TABLE "WEIGHT_INFO"
(WEIGHT_ID     INTEGER
            PRIMARY KEY,
    WEIGHT_IN_KG  INTEGER,
    WEIGHT_IN_LBS INTEGER
);

CREATE TABLE "PLAYERINFO"
(ELITEID           INTEGER
            PRIMARY KEY,
    PLAYERNAME        VARCHAR2(255),
    BIRTHDATE         VARCHAR2(255),
    BIRTHYEAR         DATE,
    BIRTHMONTH        INTEGER,
    BIRTHDAY          INTEGER,
    BIRTHPLACE        VARCHAR2(255),
    NATION            VARCHAR2(255),
    HEIGHT            INTEGER,
    WEIGHT            INTEGER,
    POSITION_INFO     VARCHAR2(255),
    SHOOTS            VARCHAR2(255),
    DRAFTYEAR         INTEGER,
    DRAFTROUND        INTEGER,
    OVERALL           INTEGER,
    OVERALLBY         VARCHAR2(255),
    CSS_RANK          INTEGER,
    SUM_7YR_GP        INTEGER,
    SUM_7YR_TOI       INTEGER,
    GP_GREATER_THAN_0 VARCHAR2(255),
    FOREIGN KEY (HEIGHT) REFERENCES "HEIGHT_INFO"(HEIGHT_ID),
    FOREIGN KEY (WEIGHT) REFERENCES "WEIGHT_INFO"(WEIGHT_ID)
);

CREATE TABLE "SEASONSTATUS"
(ELITEID   INTEGER,
    SEASON    VARCHAR2(255),
    TEAM      VARCHAR2(255),
    LEAGUE    VARCHAR2(255),
    GAMETYPE  VARCHAR2(255),
    GP        INTEGER,
    G         INTEGER,
    A         INTEGER,
    P         INTEGER,
    PIM       INTEGER,
    PLUSMINUS INTEGER,
    FOREIGN KEY (ELITEID) REFERENCES "PLAYERINFO"(ELITEID)
);

