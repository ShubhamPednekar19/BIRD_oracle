CREATE TABLE "ALL_PREVALENCES"
(ITEM                    VARCHAR2(255)
            PRIMARY KEY,
    "POPULATION TYPE"       VARCHAR2(255),
    OCCURRENCES             INTEGER,
    "POPULATION COUNT"      INTEGER,
    "PREVALENCE RATE"       FLOAT,
    "PREVALENCE PERCENTAGE" FLOAT
);

CREATE TABLE "PATIENTS"
(PATIENT    VARCHAR2(255)
            PRIMARY KEY,
    BIRTHDATE  DATE,
    DEATHDATE  DATE,
    SSN        VARCHAR2(255),
    DRIVERS    VARCHAR2(255),
    PASSPORT   VARCHAR2(255),
    PREFIX     VARCHAR2(255),
    FIRST      VARCHAR2(255),
    LAST       VARCHAR2(255),
    SUFFIX     VARCHAR2(255),
    MAIDEN     VARCHAR2(255),
    MARITAL    VARCHAR2(255),
    RACE       VARCHAR2(255),
    ETHNICITY  VARCHAR2(255),
    GENDER     VARCHAR2(255),
    BIRTHPLACE VARCHAR2(255),
    ADDRESS    VARCHAR2(255)
);

CREATE TABLE "ENCOUNTERS"
(ID                VARCHAR2(255)
            PRIMARY KEY,
    "DATE"              DATE,
    PATIENT           VARCHAR2(255),
    CODE              INTEGER,
    DESCRIPTION       VARCHAR2(255),
    REASONCODE        INTEGER,
    REASONDESCRIPTION VARCHAR2(255),
    FOREIGN KEY (PATIENT) REFERENCES "PATIENTS"(PATIENT)
);

CREATE TABLE "ALLERGIES"
("START"       VARCHAR2(255),
    STOP        VARCHAR2(255),
    PATIENT     VARCHAR2(255),
    ENCOUNTER   VARCHAR2(255),
    CODE        INTEGER,
    DESCRIPTION VARCHAR2(255),
    PRIMARY KEY (PATIENT, ENCOUNTER, CODE),
    FOREIGN KEY (ENCOUNTER) REFERENCES "ENCOUNTERS"(ID),
    FOREIGN KEY (PATIENT) REFERENCES "PATIENTS"(PATIENT)
);

CREATE TABLE "CAREPLANS"
(ID                VARCHAR2(255),
    "START"             DATE,
    STOP              DATE,
    PATIENT           VARCHAR2(255),
    ENCOUNTER         VARCHAR2(255),
    CODE              FLOAT,
    DESCRIPTION       VARCHAR2(255),
    REASONCODE        INTEGER,
    REASONDESCRIPTION VARCHAR2(255),
    FOREIGN KEY (ENCOUNTER) REFERENCES "ENCOUNTERS"(ID),
    FOREIGN KEY (PATIENT) REFERENCES "PATIENTS"(PATIENT)
);

CREATE TABLE "CONDITIONS"
("START"       DATE,
    STOP        DATE,
    PATIENT     VARCHAR2(255),
    ENCOUNTER   VARCHAR2(255),
    CODE        INTEGER,
    DESCRIPTION VARCHAR2(255),
    FOREIGN KEY (ENCOUNTER) REFERENCES "ENCOUNTERS"(ID),
    FOREIGN KEY (PATIENT) REFERENCES "PATIENTS"(PATIENT),
    FOREIGN KEY (DESCRIPTION) REFERENCES "ALL_PREVALENCES"(ITEM)
);

CREATE TABLE "IMMUNIZATIONS"
("DATE"        DATE,
    PATIENT     VARCHAR2(255),
    ENCOUNTER   VARCHAR2(255),
    CODE        INTEGER,
    DESCRIPTION VARCHAR2(255),
    PRIMARY KEY ("DATE", PATIENT, ENCOUNTER, CODE),
    FOREIGN KEY (ENCOUNTER) REFERENCES "ENCOUNTERS"(ID),
    FOREIGN KEY (PATIENT) REFERENCES "PATIENTS"(PATIENT)
);

CREATE TABLE "MEDICATIONS"
("START"             DATE,
    STOP              DATE,
    PATIENT           VARCHAR2(255),
    ENCOUNTER         VARCHAR2(255),
    CODE              INTEGER,
    DESCRIPTION       VARCHAR2(255),
    REASONCODE        INTEGER,
    REASONDESCRIPTION VARCHAR2(255),
    PRIMARY KEY ("START", PATIENT, ENCOUNTER, CODE),
    FOREIGN KEY (ENCOUNTER) REFERENCES "ENCOUNTERS"(ID),
    FOREIGN KEY (PATIENT) REFERENCES "PATIENTS"(PATIENT)
);

CREATE TABLE "OBSERVATIONS"
("DATE"        DATE,
    PATIENT     VARCHAR2(255),
    ENCOUNTER   VARCHAR2(255),
    CODE        VARCHAR2(255),
    DESCRIPTION VARCHAR2(255),
    VALUE       FLOAT,
    UNITS       VARCHAR2(255),
    FOREIGN KEY (ENCOUNTER) REFERENCES "ENCOUNTERS"(ID),
    FOREIGN KEY (PATIENT) REFERENCES "PATIENTS"(PATIENT)
);

CREATE TABLE "PROCEDURES"
("DATE"              DATE,
    PATIENT           VARCHAR2(255),
    ENCOUNTER         VARCHAR2(255),
    CODE              INTEGER,
    DESCRIPTION       VARCHAR2(255),
    REASONCODE        INTEGER,
    REASONDESCRIPTION VARCHAR2(255),
    FOREIGN KEY (ENCOUNTER) REFERENCES "ENCOUNTERS"(ID),
    FOREIGN KEY (PATIENT) REFERENCES "PATIENTS"(PATIENT)
);

CREATE TABLE "CLAIMS"
(ID             VARCHAR2(255)
        PRIMARY KEY,
    PATIENT        VARCHAR2(255)
        REFERENCES "PATIENTS",
    BILLABLEPERIOD DATE,
    ORGANIZATION   VARCHAR2(255),
    ENCOUNTER      VARCHAR2(255)
        REFERENCES "ENCOUNTERS",
    DIAGNOSIS      VARCHAR2(255),
    TOTAL          INTEGER
);

