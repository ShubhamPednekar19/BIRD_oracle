CREATE TABLE "BUSINESSES" (BUSINESS_ID INTEGER   ,
  NAME VARCHAR2(255)   ,
  ADDRESS VARCHAR2(255) DEFAULT NULL,
  CITY VARCHAR2(255) DEFAULT NULL,
  POSTAL_CODE VARCHAR2(255) DEFAULT NULL,
  LATITUDE FLOAT DEFAULT NULL,
  LONGITUDE FLOAT DEFAULT NULL,
  PHONE_NUMBER INTEGER DEFAULT NULL,
  TAX_CODE VARCHAR2(255) DEFAULT NULL,
  BUSINESS_CERTIFICATE INTEGER   ,
  APPLICATION_DATE DATE DEFAULT NULL,
  OWNER_NAME VARCHAR2(255)   ,
  OWNER_ADDRESS VARCHAR2(255) DEFAULT NULL,
  OWNER_CITY VARCHAR2(255) DEFAULT NULL,
  OWNER_STATE VARCHAR2(255) DEFAULT NULL,
  OWNER_ZIP VARCHAR2(255) DEFAULT NULL,
  PRIMARY KEY (BUSINESS_ID)
);

CREATE TABLE "INSPECTIONS" (BUSINESS_ID INTEGER   ,
  SCORE INTEGER DEFAULT NULL,
  "DATE" DATE   ,
  TYPE VARCHAR2(255)   ,
  FOREIGN KEY (BUSINESS_ID) REFERENCES "BUSINESSES" (BUSINESS_ID)
);

CREATE TABLE "VIOLATIONS" (BUSINESS_ID INTEGER   ,
  "DATE" DATE   ,
  VIOLATION_TYPE_ID VARCHAR2(255)   ,
  RISK_CATEGORY VARCHAR2(255)   ,
  DESCRIPTION VARCHAR2(255)   ,
  FOREIGN KEY (BUSINESS_ID) REFERENCES "BUSINESSES" (BUSINESS_ID)
);

