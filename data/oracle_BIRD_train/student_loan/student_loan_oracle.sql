CREATE TABLE "BOOL"
(NAME VARCHAR2(255) DEFAULT ''   
        PRIMARY KEY
);

CREATE TABLE "PERSON"
(NAME VARCHAR2(255) DEFAULT ''   
        PRIMARY KEY
);

CREATE TABLE "DISABLED"
(NAME VARCHAR2(255) DEFAULT ''   
        PRIMARY KEY,
        FOREIGN KEY (NAME) REFERENCES "PERSON" (NAME)
              ON DELETE CASCADE
);

CREATE TABLE "ENLIST"
(NAME  VARCHAR2(255)   ,
    ORGAN VARCHAR2(255)   ,
        FOREIGN KEY (NAME) REFERENCES "PERSON" (NAME)
              ON DELETE CASCADE
);

CREATE TABLE "FILED_FOR_BANKRUPCY"
(NAME VARCHAR2(255) DEFAULT ''   
        PRIMARY KEY,
        FOREIGN KEY (NAME) REFERENCES "PERSON" (NAME)
              ON DELETE CASCADE
);

CREATE TABLE "LONGEST_ABSENSE_FROM_SCHOOL"
(NAME  VARCHAR2(255) DEFAULT ''   
        PRIMARY KEY,
    MONTH INTEGER       DEFAULT 0  NULL,
        FOREIGN KEY (NAME) REFERENCES "PERSON" (NAME)
              ON DELETE CASCADE
);

CREATE TABLE "MALE"
(NAME VARCHAR2(255) DEFAULT ''   
        PRIMARY KEY,
        FOREIGN KEY (NAME) REFERENCES "PERSON" (NAME)
              ON DELETE CASCADE
);

CREATE TABLE "NO_PAYMENT_DUE"
(NAME VARCHAR2(255) DEFAULT ''   
        PRIMARY KEY,
    BOOL VARCHAR2(255)             NULL,
        FOREIGN KEY (NAME) REFERENCES "PERSON" (NAME)
              ON DELETE CASCADE,
        FOREIGN KEY (BOOL) REFERENCES "BOOL" (NAME)
              ON DELETE CASCADE
);

CREATE TABLE "UNEMPLOYED"
(NAME VARCHAR2(255) DEFAULT ''   
        PRIMARY KEY,
        FOREIGN KEY (NAME) REFERENCES "PERSON" (NAME)
              ON DELETE CASCADE
);

CREATE TABLE "ENROLLED" (NAME VARCHAR2(255)   ,
  SCHOOL VARCHAR2(255)   ,
  MONTH INTEGER DEFAULT 0 ,
  PRIMARY KEY (NAME,SCHOOL),
  FOREIGN KEY (NAME) REFERENCES "PERSON" (NAME) ON DELETE CASCADE  
);

