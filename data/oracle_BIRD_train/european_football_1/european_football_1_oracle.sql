CREATE TABLE "DIVISIONS"
(DIVISION VARCHAR2(255)   
        PRIMARY KEY,
    NAME     VARCHAR2(255),
    COUNTRY  VARCHAR2(255)
);

CREATE TABLE "MATCHS"
(DIV      VARCHAR2(255),
    "DATE"     DATE,
    HOMETEAM VARCHAR2(255),
    AWAYTEAM VARCHAR2(255),
    FTHG     INTEGER,
    FTAG     INTEGER,
    FTR      VARCHAR2(255),
    SEASON   INTEGER,
    FOREIGN KEY (DIV) REFERENCES "DIVISIONS"(DIVISION)
);

