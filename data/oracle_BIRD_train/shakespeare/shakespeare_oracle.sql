CREATE TABLE "WORKS"
(ID        INTEGER
        GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TITLE     VARCHAR2(255)    NOT NULL  ,
    LONGTITLE VARCHAR2(255)    NOT NULL  ,
    "DATE"      INTEGER NOT NULL  ,
    GENRETYPE VARCHAR2(255)    NOT NULL  
);

CREATE TABLE "CHAPTERS"
(ID          INTEGER
        GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ACT         INTEGER NOT NULL  ,
    SCENE       INTEGER NOT NULL  ,
    DESCRIPTION VARCHAR2(255)    NOT NULL  ,
    WORK_ID     INTEGER NOT NULL  
        REFERENCES "WORKS"
);

CREATE TABLE "CHARACTERS"
(ID          INTEGER
        GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    CHARNAME    VARCHAR2(255) NOT NULL  ,
    ABBREV      VARCHAR2(255) NOT NULL  ,
    DESCRIPTION VARCHAR2(255) NOT NULL  
);

CREATE TABLE "PARAGRAPHS"
(ID           INTEGER
        GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    PARAGRAPHNUM INTEGER           NOT NULL  ,
    PLAINTEXT    VARCHAR2(255)              NOT NULL  ,
    CHARACTER_ID INTEGER           NOT NULL  
        REFERENCES "CHARACTERS",
    CHAPTER_ID   INTEGER DEFAULT 0 NOT NULL  
        REFERENCES "CHAPTERS"
);

