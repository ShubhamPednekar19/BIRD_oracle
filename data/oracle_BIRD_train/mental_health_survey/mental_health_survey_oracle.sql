CREATE TABLE "QUESTION"
(QUESTIONTEXT VARCHAR2(255),
    QUESTIONID   INTEGER
        CONSTRAINT QUESTION_PK
            PRIMARY KEY
);

CREATE TABLE "SURVEY"
(SURVEYID    INTEGER
        CONSTRAINT SURVEY_PK
            PRIMARY KEY,
    DESCRIPTION VARCHAR2(255)
);

CREATE TABLE "ANSWER"
(ANSWERTEXT VARCHAR2(255),
    SURVEYID   INTEGER
        CONSTRAINT ANSWER_SURVEY_SURVEYID_FK
            REFERENCES "SURVEY",
    USERID     INTEGER,
    QUESTIONID INTEGER
        CONSTRAINT ANSWER_QUESTION_QUESTIONID_FK
            REFERENCES "QUESTION",
    CONSTRAINT ANSWER_PK
        PRIMARY KEY (USERID, QUESTIONID)
);

