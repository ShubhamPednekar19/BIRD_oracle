CREATE TABLE "EPISODE"
(EPISODE_ID       VARCHAR2(255)
        CONSTRAINT EPISODE_PK
            PRIMARY KEY,
    SEASON           INTEGER,
    EPISODE          INTEGER,
    NUMBER_IN_SERIES INTEGER,
    TITLE            VARCHAR2(255),
    SUMMARY          VARCHAR2(255),
    AIR_DATE         VARCHAR2(255),
    EPISODE_IMAGE    VARCHAR2(255),
    RATING           FLOAT,
    VOTES            INTEGER
);

CREATE TABLE "PERSON"
(NAME          VARCHAR2(255)
        PRIMARY KEY,
    BIRTHDATE     VARCHAR2(255),
    BIRTH_NAME    VARCHAR2(255),
    BIRTH_PLACE   VARCHAR2(255),
    BIRTH_REGION  VARCHAR2(255),
    BIRTH_COUNTRY VARCHAR2(255),
    HEIGHT_METERS FLOAT,
    NICKNAME      VARCHAR2(255)
);

CREATE TABLE "AWARD"
(AWARD_ID       INTEGER
            PRIMARY KEY,
    ORGANIZATION   VARCHAR2(255),
    YEAR           INTEGER,
    AWARD_CATEGORY VARCHAR2(255),
    AWARD          VARCHAR2(255),
    PERSON         VARCHAR2(255),
    ROLE           VARCHAR2(255),
    EPISODE_ID     VARCHAR2(255),
    SEASON         VARCHAR2(255),
    SONG           VARCHAR2(255),
    RESULT         VARCHAR2(255),
    FOREIGN KEY (PERSON) REFERENCES "PERSON"(NAME),
    FOREIGN KEY (EPISODE_ID) REFERENCES "EPISODE"(EPISODE_ID)
);

CREATE TABLE "CHARACTER_AWARD"
(AWARD_ID  INTEGER,
    CHARACTER VARCHAR2(255),
    FOREIGN KEY (AWARD_ID) REFERENCES "AWARD"(AWARD_ID)
);

CREATE TABLE "CREDIT"
(EPISODE_ID VARCHAR2(255),
    CATEGORY   VARCHAR2(255),
    PERSON     VARCHAR2(255),
    ROLE       VARCHAR2(255),
    CREDITED   VARCHAR2(255),
    FOREIGN KEY (EPISODE_ID) REFERENCES "EPISODE"(EPISODE_ID),
    FOREIGN KEY (PERSON) REFERENCES "PERSON"(NAME)
);

CREATE TABLE "KEYWORD"
(EPISODE_ID VARCHAR2(255),
    KEYWORD    VARCHAR2(255),
    PRIMARY KEY (EPISODE_ID, KEYWORD),
    FOREIGN KEY (EPISODE_ID) REFERENCES "EPISODE"(EPISODE_ID)
);

CREATE TABLE "VOTE"
(EPISODE_ID VARCHAR2(255),
    STARS      INTEGER,
    VOTES      INTEGER,
    PERCENT    FLOAT,
    FOREIGN KEY (EPISODE_ID) REFERENCES "EPISODE"(EPISODE_ID)
);

