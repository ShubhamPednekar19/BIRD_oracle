CREATE TABLE "AWARDS_PLAYERS"
(PLAYERID VARCHAR2(255)   ,
    AWARD    VARCHAR2(255)   ,
    YEAR     INTEGER            ,
    LGID     VARCHAR2(255) NULL,
    NOTE     VARCHAR2(255) NULL,
